import { Effect, FileSystem, Path } from 'effect';
import { NAME } from '@norbital-ai/bolt/tooling';
import type { Discovered } from './discover.ts';

/** Each path supplies the type anchor for its declaration's callbacks. */
export const writeDeclarations = Effect.fn('bolt.writeDeclarations')(function* (
	root: string,
	files: readonly Discovered[]
) {
	const fs = yield* FileSystem.FileSystem;
	const path = yield* Path.Path;
	for (const [role, folder, member] of [
		['model', 'models', 'model'],
		['integration_definition', 'integrations', 'integration']
	] as const) {
		const names = new Set(
			files
				.filter(
					(file) =>
						file.role === role && !file.path.startsWith('src/system/') && NAME.test(file.name)
				)
				.map((file) => file.name)
		);
		const directory = path.join(root, '.norbital', folder);
		if (names.size === 0 && !(yield* fs.exists(directory))) continue;
		yield* fs.makeDirectory(directory, { recursive: true });
		for (const entry of yield* fs.readDirectory(directory))
			if (entry.endsWith('.ts') && !names.has(entry.slice(0, -3)))
				yield* fs.remove(path.join(directory, entry));
		for (const name of names) {
			const target = path.join(directory, `${name}.ts`);
			const declarationType = member === 'model' ? 'Model' : 'Integration';
			const literalType = `${declarationType}Literal`;
			const inputType = `${declarationType}LiteralInput`;
			const identity = JSON.stringify(name);
			const constraint = member === 'model' ? literalType : `${literalType}<${identity}>`;
			const text = `// Generated by bolt from the declaration path.
import { bind_${member}, type ${declarationType}, type ${literalType}, type ${inputType} } from '@norbital-ai/bolt/declarations';
const declaration = /* @__PURE__ */ bind_${member}(${identity});
/* @__NO_SIDE_EFFECTS__ */
export function ${member}<const S extends ${constraint}>(spec: ${inputType}<${identity}, S>): ${declarationType}<${identity}, S> {
	return declaration<S>(spec);
}
`;
			if (!(yield* fs.exists(target)) || (yield* fs.readFileString(target)) !== text)
				yield* Effect.scoped(
					Effect.gen(function* () {
						const temporary = yield* fs.makeTempFileScoped({ directory, prefix: '.binding-' });
						yield* fs.writeFileString(temporary, text);
						yield* fs.rename(temporary, target);
					})
				);
		}
	}
});
