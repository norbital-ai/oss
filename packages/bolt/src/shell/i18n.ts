import { Effect, Result } from 'effect';
import type { UiTextKey } from '@norbital-ai/ui';

export const LOCALES = ['en', 'zh'] as const;
type FrameworkLocale = (typeof LOCALES)[number];
/** Each locale's name in its own language: the switch's label. */
export const LANGUAGE: { readonly [l in FrameworkLocale]: string } = { en: 'English', zh: '中文' };
const CHOICE = 'bolt.locale';

/** The viewer's chosen locale, else the workspace's. Storage may be absent or refuse (a private window). */
export function chosenLocale(workspace: string): string {
	// Synchronous browser preference at component initialization; storage denial uses the workspace locale.
	return Result.getOrElse(
		Result.try({
			try: () => localStorage.getItem(CHOICE) ?? workspace,
			catch: (cause) => ({ _tag: 'LocaleStorageFailed' as const, cause })
		}),
		() => workspace
	);
}
/** Remembers a browser preference then reloads every localized component. */
export const setLocale = (locale: string): Effect.Effect<void> =>
	Effect.try({
		try: () => localStorage.setItem(CHOICE, locale),
		catch: (cause) => ({ _tag: 'LocaleStorageFailed' as const, cause })
	}).pipe(
		Effect.catch(() => Effect.void),
		Effect.andThen(Effect.sync(() => location.reload()))
	);

