export const LOCALES = PERSONAL_LOCALES;
type FrameworkLocale = (typeof LOCALES)[number];
/** Whether Bolt ships built-in framework translations for this locale (`en`, `zh`, and their subtags). */
export const is_native_locale = (locale: string): boolean => {
	const base = locale.trim().toLowerCase().split('-')[0] ?? '';
	return base === 'en' || base === 'zh';
};
/** Each framework locale's name in its own language. */
export const LANGUAGE: { readonly [l in FrameworkLocale]: string } = { en: 'English', zh: '中文' };
const LANGUAGE_OVERRIDES: { readonly [code: string]: string } = { en: 'English', zh: '中文' };
/** A BCP-47 language tag's native endonym (e.g. `'en'` → `'English'`, `'zh'` → `'中文'`, `'ja'` → `'日本語'`). */
export function languageLabel(code: string): string {
	const trimmed = code.trim();
	if (trimmed === '') return code;
	const override = LANGUAGE_OVERRIDES[trimmed.toLowerCase()];
	if (override !== undefined) return override;
	const resolved = Result.try({
		try: () => {
			const display = new Intl.DisplayNames([trimmed], { type: 'language' }).of(trimmed);
			if (display === undefined || display.trim() === '') return trimmed;
			return display.charAt(0).toLocaleUpperCase(trimmed) + display.slice(1);
		},
		catch: () => trimmed
	});
	return Result.isSuccess(resolved) ? resolved.success : trimmed;
}
const CHOICE = 'bolt.locale';

/** The viewer's chosen locale, else the workspace's. Storage may be absent or refuse (a private window). */
export function chosenLocale(workspace: string): string {
	// Synchronous browser preference at component initialization; storage denial uses the workspace locale.
	return Result.getOrElse(
		Result.try({
			try: () => localStorage.getItem(CHOICE) ?? workspace,
			catch: (cause) => ({ _tag: 'LocaleStorageFailed' as const, cause })
		}),
		() => workspace
	);
}
/** Refreshes the browser cache then reloads every localized component. */
export const setLocale = (locale: string): Effect.Effect<void> =>
	Effect.try({
		try: () => localStorage.setItem(CHOICE, locale),
		catch: (cause) => ({ _tag: 'LocaleStorageFailed' as const, cause })
	}).pipe(
		Effect.catch(() => Effect.void),
		Effect.andThen(Effect.sync(() => location.reload()))
	);

/** Handle text keeps repeated separators and leading/trailing whitespace exactly as authored. */
export const handle_words = (value: string): string => value.replaceAll('_', ' ');
/** Agent names uppercase their first character, including a leading Unicode letter. */
export const humanise = (value: string): string =>
	handle_words(value).replace(/^./, (character) => character.toUpperCase());
/** Native form labels and verbs uppercase an initial ASCII word character only. */
export const humanise_word = (value: string): string =>
	handle_words(value).replace(/^\w/, (character) => character.toUpperCase());

export const BRIEF_TIMESTAMP = { dateStyle: 'medium', timeStyle: 'short' } as const;
/** Native display semantics: the runtime locale remains the default, and invalid text reads as Invalid Date. */
export const date_time = (
	value: string,
	locale?: Intl.LocalesArgument,
	options?: Intl.DateTimeFormatOptions
): string => new Date(value).toLocaleString(locale, options);
/** Both shell USD views retain Intl's runtime locale and currency defaults; session costs show up to four decimals. */
export const usd = (value: number, maximum_fraction_digits?: number): string =>
	new Intl.NumberFormat(undefined, {
		style: 'currency',
		currency: 'USD',
		...(maximum_fraction_digits === undefined
			? {}
			: { maximumFractionDigits: maximum_fraction_digits })
	}).format(value);

