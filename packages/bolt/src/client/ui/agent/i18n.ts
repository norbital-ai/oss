export type TenantMessageCatalogs = {
	readonly en: Readonly<Record<string, string>>;
	readonly zh?: Readonly<Record<string, string>>;
};

/**
 * Spreads tenant catalogs onto the already-defined ui+bolt pair.
 * Tenant zh may omit keys, so the tenant slice is never passed through defineMessages.
 *
 * The return type is declared open rather than inferred. Inference produced the closed set of
 * ui+bolt literal keys — an object spread does not carry an index signature through — so the one
 * thing this function exists to do, carry workspace-authored keys a package cannot know, did not
 * typecheck at the call site.
 */
export function mergeBoltAgentMessages(
	uiMessages: LocaleCatalogs,
	tenantMessages?: TenantMessageCatalogs
): {
	readonly en: Readonly<Record<string, string>>;
	readonly zh: Readonly<Record<string, string>>;
} {
	const defined = defineMessages({
		en: { ...uiMessages.en, ...boltAgentMessages.en },
		zh: { ...uiMessages.zh, ...boltAgentMessages.zh }
	});
	// Annotated rather than inferred: `?? {}` widens to a union with the empty object literal, and
	// spreading that union drops the index signature — so the merged catalog typed as a closed set
	// of ui+bolt keys and rejected every tenant key it exists to carry.
	const tenantEn: Readonly<Record<string, string>> = tenantMessages?.en ?? {};
	const tenantZh: Readonly<Record<string, string>> = tenantMessages?.zh ?? {};
	return {
		en: { ...defined.en, ...tenantEn },
		zh: { ...defined.zh, ...tenantZh }
	};
}
