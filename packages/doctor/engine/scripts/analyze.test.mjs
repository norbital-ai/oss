const sourceExtensions = ['.ts', '.tsx', '.mts', '.cts', '.js', '.jsx', '.mjs', '.cjs', '.svelte'];

function write(path, content) {
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, content);
}

const generatedHeader = /^\s*(?:\/\/|\/\*)[^\n]{0,120}(?:@generated|generated by|do not edit)/i;

function scannerExcluded(root, file) {
	return (
		/\.d\.(?:ts|mts|cts)$/.test(file) ||
		/(?:^|\/)[^/]+\.(?:generated|gen)(?:\.svelte)?\.(?:[cm]?[jt]sx?|svelte)$/.test(file) ||
		/(^|\/)(node_modules|\.yalc|build|dist|coverage|generated|\.generated|\.svelte-kit(?:-e2e)?|\.tmp|\.data|\.agents|\.opencode)(\/|$)/.test(
			file
		) ||
		/(^|\/)(test|tests|e2e|__tests__)(\/|$)/.test(file) ||
		/\.(test|spec)\.[^.]+$/.test(file) ||
		generatedHeader.test(readFileSync(join(root, file), 'utf8').slice(0, 500))
	);
}

function receiptInventory(root) {
	const sources = [];
	const visit = (directory) => {
		for (const entry of readdirSync(directory, { withFileTypes: true })) {
			const path = join(directory, entry.name);
			if (entry.isDirectory()) visit(path);
			else if (entry.isFile()) {
				const local = relative(root, path).split(sep).join('/');
				if (
					sourceExtensions.some((extension) => entry.name.endsWith(extension)) &&
					!scannerExcluded(root, local)
				)
					sources.push(local);
			}
		}
	};
	visit(root);
	sources.sort();
	const inputs = new Set(sources);
	for (const file of sources) {
		let directory = dirname(join(root, file));
		while (directory === root || directory.startsWith(`${root}${sep}`)) {
			for (const name of ['package.json', 'tsconfig.json', 'jsconfig.json']) {
				const candidate = join(directory, name);
				if (existsSync(candidate)) inputs.add(relative(root, candidate).split(sep).join('/'));
			}
			if (directory === root) break;
			directory = dirname(directory);
		}
	}
	const digest = createHash('sha256');
	for (const file of [...inputs].sort()) {
		const fileHash = createHash('sha256')
			.update(readFileSync(join(root, file)))
			.digest('hex');
		digest.update(`${file}\0${fileHash}\n`);
	}
	return { files: sources.length, digest: `sha256:${digest.digest('hex')}` };
}

function makeReceipt(root, rows = [], { typeAware = true } = {}) {
	const directory = join(root, '.norbital/diagnosis');
	const catalogue = join(directory, 'findings.tsv');
	const content = rows.join('\n') + (rows.length ? '\n' : '');
	write(catalogue, content);
	const inventory = receiptInventory(root);
	const counts = {
		error: 0,
		warning: 0,
		hint: 0,
		total: rows.length,
		principles: {
			simplicity: 0,
			straightforwardness: 0,
			modularity: 0,
			testability: 0,
			efficiency: 0,
			typeSafety: 0,
			colocation: 0,
			noBloat: 0
		}
	};
	for (const row of rows) {
		const [severity, , , , , encoded] = row.split('\t');
		counts[severity] += 1;
		for (const principle of encoded.split(',')) {
			const key =
				principle === 'no-bloat'
					? 'noBloat'
					: principle === 'type-safety'
						? 'typeSafety'
						: principle;
			counts.principles[key] += 1;
		}
	}
	const receipt = join(directory, 'receipt.json');
	write(
		receipt,
		JSON.stringify({
			schemaVersion: 5,
			kind: 'repository-health-static-receipt',
			scannerVersion: 31,
			root: realpathSync(root),
			scope: 'all',
			includeTests: false,
			tiers: { syntactic: true, graph: true, typeAware },
			files: inventory.files,
			sourceInventoryDigest: inventory.digest,
			ruleSetDigest: `sha256:${'1'.repeat(64)}`,
			catalogueDigest: `sha256:${createHash('sha256').update(content).digest('hex')}`,
			counts,
			findings: 'findings.tsv',
			complete: true
		})
	);
	return receipt;
}

