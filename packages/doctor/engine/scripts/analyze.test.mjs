test('records tier coverage and refuses a release gate whose type-aware tier never ran', (context) => {
	const { root } = fixture();
	context.after(() => rmSync(root, { recursive: true, force: true }));

	// A syntactic+graph scan is valid evidence and reports as such.
	const fast = makeReceipt(root, [], { typeAware: false });
	const scanned = run([root], [fast]);
	const report = JSON.parse(scanned.stdout);
	assert.equal(report.quality.coverage.tiers.typeAware, false);
	assert.deepEqual(report.quality.coverage.rootsWithoutTypeAware, [realpathSync(root)]);
	assert.notEqual(report.verdict, 'incomplete');
	assert.match(run([root], [fast], ['--format', 'markdown']).stdout, /type-aware not run/);

	// Asking for the tier and not having it is incomplete evidence, not a pass.
	const required = run([root], [fast], ['--require-type-aware']);
	assert.equal(required.status, 2);
	assert.equal(JSON.parse(required.stdout).verdict, 'incomplete');

	// The same gate is satisfied once the tier actually ran.
	const full = makeReceipt(root, [], { typeAware: true });
	const satisfied = run([root], [full], ['--require-type-aware']);
	assert.equal(JSON.parse(satisfied.stdout).quality.coverage.tiers.typeAware, true);
	assert.notEqual(JSON.parse(satisfied.stdout).verdict, 'incomplete');

	// A receipt that does not state its tiers at all is not authenticatable.
	const receiptPath = join(root, '.norbital/diagnosis/receipt.json');
	const withoutTiers = JSON.parse(readFileSync(receiptPath, 'utf8'));
	delete withoutTiers.tiers;
	writeFileSync(receiptPath, JSON.stringify(withoutTiers));
	const unstated = run([root], [receiptPath]);
	assert.equal(unstated.status, 2);
	assert.match(unstated.stderr, /fields do not match schema/);

	// So is one that claims a tier ran without saying whether it did.
	writeFileSync(
		receiptPath,
		JSON.stringify({ ...withoutTiers, tiers: { syntactic: true, graph: true } })
	);
	const malformed = run([root], [receiptPath]);
	assert.equal(malformed.status, 2);
	assert.match(malformed.stderr, /does not record tier coverage/);
});

