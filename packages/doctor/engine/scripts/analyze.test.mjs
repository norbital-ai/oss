function run(roots, receipts = [], extra = []) {
	const args = [analyzer];
	for (const root of roots) args.push('--root', root);
	for (const receipt of receipts) args.push('--receipt', receipt);
	args.push('--format', 'json', ...extra);
	return spawnSync(process.execPath, args, { encoding: 'utf8' });
}

