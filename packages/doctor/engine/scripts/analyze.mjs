/** Walk selected roots in lexical order while excluding generated and dependency-owned trees. */
function collectSourceFiles(roots) {
	const files = [];
	// `.doctorignore` is honored here as well as in scannerExcluded. The two walks are cross-checked
	// by digest, so a tree excluded from one and not the other reports as unscanned, not as scoped.
	let currentRoot = '';
	const visit = (directory) => {
		for (const entry of readdirSync(directory, { withFileTypes: true }).sort((a, b) =>
			a.name.localeCompare(b.name)
		)) {
			if (entry.isDirectory() && IGNORED_DIRECTORIES.has(entry.name)) continue;
			const path = join(directory, entry.name);
			if (ignoredFile(currentRoot, relative(currentRoot, path).split(sep).join('/'))) continue;
			if (entry.isDirectory()) visit(path);
			else if (
				entry.isFile() &&
				SOURCE_EXTENSIONS.has(extname(entry.name)) &&
				!/\.d\.(?:ts|mts|cts)$/.test(entry.name) &&
				!/\.(?:generated|gen)(?:\.[^.]+)+$/.test(entry.name) &&
				!hasGeneratedHeader(path)
			)
				files.push(path);
		}
	};
	for (const root of roots) {
		if (!existsSync(root) || !statSync(root).isDirectory())
			throw new Error(`root is not a directory: ${root}`);
		currentRoot = root;
		visit(root);
	}
	return [...new Set(files)].sort();
}

/** Classify mixed Svelte/HTML/CSS lines without treating quoted comment markers as comments. */
function mixedLineCounts(source) {
	const lines = source.split(/\r?\n/);
	if (source.endsWith('\n')) lines.pop();
	const state = { block: false, html: false, quote: '' };
	let code = 0;
	let comments = 0;
	let blank = 0;
	for (const line of lines) {
		let hasCode = false;
		let hasComment = state.block || state.html;
		let escaped = false;
		for (let index = 0; index < line.length; index += 1) {
			const char = line[index];
			const two = line.slice(index, index + 2);
			const three = line.slice(index, index + 3);
			const four = line.slice(index, index + 4);
			if (state.block) {
				hasComment = true;
				if (two === '*/') {
					state.block = false;
					index += 1;
				}
				continue;
			}
			if (state.html) {
				hasComment = true;
				if (three === '-->') {
					state.html = false;
					index += 2;
				}
				continue;
			}
			if (state.quote !== '') {
				hasCode = true;
				if (escaped) {
					escaped = false;
					continue;
				}
				if (char === '\\') {
					escaped = true;
					continue;
				}
				if (char === state.quote) state.quote = '';
				continue;
			}
			if (two === '//') {
				hasComment = true;
				break;
			}
			if (two === '/*') {
				hasComment = true;
				state.block = true;
				index += 1;
				continue;
			}
			if (four === '<!--') {
				hasComment = true;
				state.html = true;
				index += 3;
				continue;
			}
			if (char === '"' || char === "'" || char === '`') {
				state.quote = char;
				hasCode = true;
				continue;
			}
			if (!/\s/.test(char)) hasCode = true;
		}
		if (state.quote !== '`') state.quote = '';
		if (hasCode) code += 1;
		else if (hasComment) comments += 1;
		else blank += 1;
	}
	return { physical: lines.length, code, comments, blank };
}

/** Classify JS/TS with the compiler scanner so template-expression comments remain comments. */
function scriptLineCounts(source) {
	const lines = source.split(/\r?\n/);
	if (source.endsWith('\n')) lines.pop();
	const code = new Set();
	const comments = new Set();
	const starts = [0];
	for (let index = 0; index < source.length; index += 1)
		if (source[index] === '\n') starts.push(index + 1);
	const lineAt = (position) => {
		let low = 0;
		let high = starts.length - 1;
		while (low <= high) {
			const middle = Math.floor((low + high) / 2);
			if (starts[middle] <= position) low = middle + 1;
			else high = middle - 1;
		}
		return Math.max(0, high);
	};
	const mark = (set, start, end) => {
		if (end <= start) return;
		const first = lineAt(start);
		const last = lineAt(Math.max(start, end - 1));
		for (let line = first; line <= last && line < lines.length; line += 1) set.add(line);
	};
	const scanner = ts.createScanner(ts.ScriptTarget.Latest, false, ts.LanguageVariant.JSX, source);
	for (let token = scanner.scan(); token !== ts.SyntaxKind.EndOfFileToken; token = scanner.scan()) {
		const start = scanner.getTokenPos();
		const end = scanner.getTextPos();
		if (
			token === ts.SyntaxKind.WhitespaceTrivia ||
			token === ts.SyntaxKind.NewLineTrivia ||
			token === ts.SyntaxKind.ConflictMarkerTrivia
		)
			continue;
		if (
			token === ts.SyntaxKind.SingleLineCommentTrivia ||
			token === ts.SyntaxKind.MultiLineCommentTrivia
		)
			mark(comments, start, end);
		else mark(code, start, end);
	}
	let commentLines = 0;
	let blank = 0;
	for (let line = 0; line < lines.length; line += 1) {
		if (code.has(line)) continue;
		if (comments.has(line)) commentLines += 1;
		else blank += 1;
	}
	return { physical: lines.length, code: code.size, comments: commentLines, blank };
}

/** Classify physical lines without allowing comments or blank space to count as code. */
function lineCounts(path, source) {
	return path.endsWith('.svelte') ? mixedLineCounts(source) : scriptLineCounts(source);
}

/** Extract component scripts for compiler analysis while LOC continues to cover the whole Svelte file. */
function analyzableSource(path, source) {
	if (!path.endsWith('.svelte')) return source;
	return [...source.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)]
		.map((match) => match[1])
		.join('\n');
}

/** Parse package and compiler alias maps once so graph edges follow the repository's declarations. */
function moduleMappings(owner) {
	const aliases = [];
	let order = 0;
	const manifestPath = join(owner.root, 'package.json');
	if (existsSync(manifestPath)) {
		const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
		for (const [pattern, target] of Object.entries(manifest.imports ?? {})) {
			// A manifest points an alias at build output; the source that produces it is what the
			// graph holds. `exportedStems` already does this for `exports`, and omitting it here left
			// `#lib/*` -> `./build/*` resolving into a directory the scan never reads, so bolt's
			// internal imports produced no edges at all.
			const targets = stringTargets(target)
				.map((item) =>
					item
						.replace(/^\.\/(?:build|dist)\//, './src/')
						.replace(/\.d\.(?:ts|mts|cts)$/, '')
						.replace(/\.(?:js|jsx|mjs|cjs)$/, '')
				)
				.map((item) => resolve(owner.root, item));
			if (targets.length > 0) aliases.push({ pattern, targets, order: order++ });
		}
	}
	let configDirectory = owner.root;
	let config;
	while (
		configDirectory === owner.scanRoot ||
		configDirectory.startsWith(`${owner.scanRoot}${sep}`)
	) {
		config = ['tsconfig.json', 'jsconfig.json']
			.map((name) => join(configDirectory, name))
			.find(existsSync);
		if (config || configDirectory === owner.scanRoot) break;
		configDirectory = dirname(configDirectory);
	}
	if (config) {
		const loaded = ts.readConfigFile(config, ts.sys.readFile);
		if (!loaded.error) {
			const parsed = ts.parseJsonConfigFileContent(
				loaded.config,
				ts.sys,
				dirname(config),
				undefined,
				config
			);
			const base = parsed.options.baseUrl ?? parsed.options.pathsBasePath ?? dirname(config);
			for (const [pattern, targets] of Object.entries(parsed.options.paths ?? {})) {
				aliases.push({
					pattern,
					targets: targets.map((target) => resolve(base, target)),
					order: order++
				});
			}
		}
	}
	return aliases.sort(
		(a, b) =>
			b.pattern.replace('*', '').length - a.pattern.replace('*', '').length || a.order - b.order
	);
}

/** Flatten conditional exports/imports; the graph conservatively includes every source target. */
function stringTargets(value) {
	if (typeof value === 'string') return [value];
	if (Array.isArray(value)) return value.flatMap(stringTargets);
	if (value && typeof value === 'object') return Object.values(value).flatMap(stringTargets);
	return [];
}

/** Apply one exact or single-star subpath pattern. */
function mappedStems(specifier, mapping) {
	const star = mapping.pattern.indexOf('*');
	if (star < 0) return specifier === mapping.pattern ? mapping.targets : [];
	const prefix = mapping.pattern.slice(0, star);
	const suffix = mapping.pattern.slice(star + 1);
	if (!specifier.startsWith(prefix) || !specifier.endsWith(suffix)) return [];
	const captured = specifier.slice(prefix.length, specifier.length - suffix.length);
	return mapping.targets.map((target) => target.replaceAll('*', captured));
}

/** Select every source target behind a public package export, including conditional branches. */
function exportedStems(owner, subpath) {
	const manifest = join(owner.root, 'package.json');
	if (!existsSync(manifest)) return [];
	const declared = JSON.parse(readFileSync(manifest, 'utf8')).exports;
	const request = subpath === '' ? '.' : `./${subpath}`;
	const entries =
		typeof declared === 'string' || Array.isArray(declared)
			? [['.', declared]]
			: declared &&
				  typeof declared === 'object' &&
				  !Object.keys(declared).some((key) => key.startsWith('.'))
				? [['.', declared]]
				: Object.entries(declared ?? {});
	for (const [pattern, value] of entries) {
		const star = pattern.indexOf('*');
		let captured = '';
		if (star < 0) {
			if (pattern !== request) continue;
		} else {
			const prefix = pattern.slice(0, star);
			const suffix = pattern.slice(star + 1);
			if (!request.startsWith(prefix) || !request.endsWith(suffix)) continue;
			captured = request.slice(prefix.length, request.length - suffix.length);
		}
		return stringTargets(value).map((selected) => {
			const target = selected
				.replaceAll('*', captured)
				.replace(/^\.\/(?:build|dist)\//, './src/')
				.replace(/\.d\.(?:ts|mts|cts)$/, '')
				.replace(/\.(?:js|jsx|mjs|cjs)$/, '');
			return resolve(owner.root, target);
		});
	}
	return [];
}

/** Locate package ownership once per directory and retain names for workspace import resolution. */
function packageFor(path, scanRoot, rootId, cache) {
	let directory = dirname(path);
	const visited = [];
	while (true) {
		if (cache.has(directory)) {
			const found = cache.get(directory);
			for (const item of visited) cache.set(item, found);
			return found;
		}
		visited.push(directory);
		const manifest = join(directory, 'package.json');
		if (existsSync(manifest)) {
			let name = basename(directory);
			try {
				name = JSON.parse(readFileSync(manifest, 'utf8')).name ?? name;
			} catch {
				/* ownership survives invalid metadata */
			}
			const packagePath = relative(scanRoot, directory).split(sep).join('/') || '.';
			const found = {
				root: directory,
				name,
				scanRoot,
				id: `${rootId}/${name}@${packagePath}`
			};
			for (const item of visited) cache.set(item, found);
			return found;
		}
		const parent = dirname(directory);
		if (parent === directory || directory === scanRoot) {
			const found = {
				root: directory,
				name: basename(directory),
				scanRoot,
				id: `${rootId}/${basename(directory)}@.`
			};
			for (const item of visited) cache.set(item, found);
			return found;
		}
		directory = parent;
	}
}

/** Derive a stable concept from package ownership and the first two directories below src. */
function conceptFor(path, owner) {
	const parts = relative(owner.root, path).split(sep);
	const sourceIndex = parts.indexOf('src');
	const owned = sourceIndex >= 0 ? parts.slice(sourceIndex + 1, -1) : parts.slice(0, 1);
	const concept = owned.slice(0, 2).join('/') || 'root';
	return `${owner.id}:${concept}`;
}

/** Group child concepts beneath the first owned source directory: one deterministic domain pillar. */
function pillarFor(path, owner) {
	const parts = relative(owner.root, path).split(sep);
	const sourceIndex = parts.indexOf('src');
	const owned = sourceIndex >= 0 ? parts.slice(sourceIndex + 1, -1) : parts.slice(0, -1);
	return `${owner.id}:${owned[0] ?? 'root'}`;
}

const LOCALITY_WEIGHTS = {
	sameDirectory: 1,
	parentChild: 0.9,
	sameConcept: 0.75,
	samePillar: 0.6,
	samePackage: 0.35,
	crossPackage: 0.1,
	crossRoot: 0
};

function emptyLocality() {
	return Object.fromEntries(Object.keys(LOCALITY_WEIGHTS).map((name) => [name, 0]));
}

function isDirectoryAncestor(parent, child) {
	return parent !== child && child.startsWith(`${parent}${sep}`);
}

/** Classify a resolved module edge by physical ownership distance. */
function importLocality(from, target) {
	if (from.root.id !== target.root.id) return 'crossRoot';
	if (from.owner.id !== target.owner.id) return 'crossPackage';
	const fromDirectory = dirname(from.path);
	const targetDirectory = dirname(target.path);
	if (fromDirectory === targetDirectory) return 'sameDirectory';
	if (
		isDirectoryAncestor(fromDirectory, targetDirectory) ||
		isDirectoryAncestor(targetDirectory, fromDirectory)
	)
		return 'parentChild';
	if (from.concept === target.concept) return 'sameConcept';
	if (from.pillar === target.pillar) return 'samePillar';
	return 'samePackage';
}

function localityScore(counts) {
	const total = Object.values(counts).reduce((sum, count) => sum + count, 0);
	if (total === 0) return 100;
	const weighted = Object.entries(counts).reduce(
		(sum, [name, count]) => sum + LOCALITY_WEIGHTS[name] * count,
		0
	);
	return Math.round((100 * weighted * 1_000_000) / total) / 1_000_000;
}

/** Recognize tests independently of package layout so production metrics cannot be padded by them. */
function isTestPath(path) {
	const normalized = path.split(sep).join('/');
	return (
		/\/(?:test|tests|e2e|__tests__)\//.test(normalized) ||
		/\.(?:test|spec)\.[^.]+$/.test(normalized)
	);
}

/** Require a package test command that can actually select the test source. */
function isConfiguredTest(path, owner) {
	const manifest = join(owner.root, 'package.json');
	if (!existsSync(manifest)) return false;
	let scripts;
	try {
		scripts = JSON.parse(readFileSync(manifest, 'utf8')).scripts ?? {};
	} catch {
		return false;
	}
	const commands = Object.entries(scripts)
		.filter(([name]) => name === 'test' || name.startsWith('test:'))
		.map(([, command]) => command)
		.filter((command) => typeof command === 'string');
	const local = relative(owner.root, path).split(sep).join('/');
	for (const command of commands) {
		if (/\b(?:vitest|jest|mocha|ava|playwright)\b/.test(command)) return true;
		if (!/\bnode\b[^&|;]*\s--test\b/.test(command)) {
			if (command.includes(local) || command.includes(basename(local))) return true;
			continue;
		}
		const tail =
			command
				.split(/\s--test(?:=\S+)?\s*/)
				.at(-1)
				?.split(/(?:&&|\|\||;)/, 1)[0] ?? '';
		const patterns = tail
			.split(/\s+/)
			.map((item) => item.replace(/^['"]|['"]$/g, ''))
			.filter((item) => item !== '' && !item.startsWith('-'));
		if (patterns.length === 0) return true;
		for (const pattern of patterns)
			try {
				if (matchesGlob(local, pattern) || local === pattern) return true;
			} catch {
				if (local === pattern) return true;
			}
	}
	return false;
}

/** Return a declaration name suitable for stable evidence, including assigned arrow functions. */
function declarationName(node) {
	if (node.name && ts.isIdentifier(node.name)) return node.name.text;
	if (
		(ts.isArrowFunction(node) || ts.isFunctionExpression(node)) &&
		ts.isVariableDeclaration(node.parent) &&
		ts.isIdentifier(node.parent.name)
	)
		return node.parent.name.text;
	return '<anonymous>';
}

function containingClass(node) {
	let current = node.parent;
	while (current) {
		if (ts.isClassDeclaration(current) || ts.isClassExpression(current)) return current;
		current = current.parent;
	}
	return null;
}

function className(node, file) {
	if (node.name && ts.isIdentifier(node.name)) return node.name.text;
	if (
		ts.isClassExpression(node) &&
		ts.isVariableDeclaration(node.parent) &&
		ts.isIdentifier(node.parent.name)
	)
		return node.parent.name.text;
	return `<class@${file.getLineAndCharacterOfPosition(node.getStart(file)).line + 1}>`;
}

function duplicateCallableKind(node) {
	if (ts.isFunctionDeclaration(node) && node.name) return 'function';
	if (
		ts.isMethodDeclaration(node) ||
		ts.isConstructorDeclaration(node) ||
		ts.isGetAccessorDeclaration(node) ||
		ts.isSetAccessorDeclaration(node)
	)
		return 'method';
	if (!(ts.isArrowFunction(node) || ts.isFunctionExpression(node))) return null;
	if (ts.isVariableDeclaration(node.parent) && ts.isIdentifier(node.parent.name)) return 'function';
	if (
		(ts.isPropertyDeclaration(node.parent) || ts.isPropertyAssignment(node.parent)) &&
		node.parent.name
	)
		return 'method';
	return null;
}

function duplicateCallableName(node, file) {
	const owner = containingClass(node);
	const ownerPrefix = owner ? `${className(owner, file)}.` : '';
	if (ts.isConstructorDeclaration(node)) return `${ownerPrefix}constructor`;
	if (node.name) return `${ownerPrefix}${node.name.getText(file)}`;
	if (
		(ts.isArrowFunction(node) || ts.isFunctionExpression(node)) &&
		(ts.isVariableDeclaration(node.parent) ||
			ts.isPropertyDeclaration(node.parent) ||
			ts.isPropertyAssignment(node.parent))
	)
		return `${ownerPrefix}${node.parent.name.getText(file)}`;
	return declarationName(node);
}

function directClassComplexity(node) {
	const metrics = node.members
		.filter((member) => member.body)
		.map((member) => complexityOf(member.body));
	return {
		cyclomatic: Math.max(1, ...metrics.map(({ cyclomatic }) => cyclomatic)),
		nesting: Math.max(0, ...metrics.map(({ nesting }) => nesting))
	};
}

function classPathway(node, file) {
	const pathway = pathwayHash(node.members.map((member) => member.getText(file)).join('\n'));
	if (!pathway) return undefined;
	const publicShape = node.members
		.map((member) =>
			ts.isConstructorDeclaration(member)
				? 'constructor'
				: `${ts.SyntaxKind[member.kind]}:${member.name?.getText(file) ?? '<anonymous>'}`
		)
		.join('|');
	return {
		...pathway,
		hash: createHash('sha256').update(`${publicShape}\0${pathway.hash}`).digest('hex').slice(0, 20)
	};
}

/** Count branch points and maximum control nesting in one function body. */
function complexityOf(body) {
	let cyclomatic = 1;
	let maximumNesting = 0;
	const visit = (node, nesting) => {
		if (
			node !== body &&
			(ts.isFunctionDeclaration(node) ||
				ts.isMethodDeclaration(node) ||
				ts.isArrowFunction(node) ||
				ts.isFunctionExpression(node) ||
				ts.isConstructorDeclaration(node) ||
				ts.isGetAccessorDeclaration(node) ||
				ts.isSetAccessorDeclaration(node))
		)
			return;
		const control =
			ts.isIfStatement(node) ||
			ts.isForStatement(node) ||
			ts.isForInStatement(node) ||
			ts.isForOfStatement(node) ||
			ts.isWhileStatement(node) ||
			ts.isDoStatement(node) ||
			ts.isCaseClause(node) ||
			ts.isCatchClause(node) ||
			ts.isConditionalExpression(node);
		if (control) cyclomatic += 1;
		if (ts.isBinaryExpression(node) && ['&&', '||', '??'].includes(node.operatorToken.getText()))
			cyclomatic += 1;
		const next = nesting + (control ? 1 : 0);
		maximumNesting = Math.max(maximumNesting, next);
		ts.forEachChild(node, (child) => visit(child, next));
	};
	visit(body, 0);
	return { cyclomatic, nesting: maximumNesting };
}

/** Normalize a non-trivial function body into a deterministic structural pathway hash. */
function pathwayHash(text) {
	const scanner = ts.createScanner(ts.ScriptTarget.Latest, true, ts.LanguageVariant.Standard, text);
	const exactTokens = [];
	const structuralTokens = [];
	let previousToken = ts.SyntaxKind.Unknown;
	for (let token = scanner.scan(); token !== ts.SyntaxKind.EndOfFileToken; token = scanner.scan()) {
		if (token === ts.SyntaxKind.Identifier || token === ts.SyntaxKind.PrivateIdentifier) {
			const identifier = scanner.getTokenText();
			const normalized = previousToken === ts.SyntaxKind.DotToken ? `$member:${identifier}` : '$id';
			exactTokens.push(normalized);
			structuralTokens.push(normalized);
		} else if (
			token === ts.SyntaxKind.StringLiteral ||
			token === ts.SyntaxKind.NumericLiteral ||
			token === ts.SyntaxKind.BigIntLiteral ||
			token === ts.SyntaxKind.NoSubstitutionTemplateLiteral ||
			token === ts.SyntaxKind.RegularExpressionLiteral ||
			token === ts.SyntaxKind.TemplateHead ||
			token === ts.SyntaxKind.TemplateMiddle ||
			token === ts.SyntaxKind.TemplateTail
		) {
			exactTokens.push(`$lit:${scanner.getTokenText()}`);
			structuralTokens.push('$lit');
		} else {
			const normalized = ts.tokenToString(token) ?? String(token);
			exactTokens.push(normalized);
			structuralTokens.push(normalized);
		}
		previousToken = token;
	}
	if (structuralTokens.length < 40) return undefined;
	const shingles = new Set();
	for (let index = 0; index <= structuralTokens.length - 5; index += 1) {
		shingles.add(
			createHash('sha256')
				.update(structuralTokens.slice(index, index + 5).join(' '))
				.digest('hex')
				.slice(0, 16)
		);
	}
	return {
		hash: createHash('sha256').update(exactTokens.join(' ')).digest('hex').slice(0, 20),
		tokens: structuralTokens.length,
		shingles: [...shingles].sort()
	};
}

const GENERIC_CALLS = new Set([
	'add',
	'at',
	'every',
	'filter',
	'find',
	'flatMap',
	'forEach',
	'get',
	'has',
	'includes',
	'join',
	'map',
	'push',
	'reduce',
	'set',
	'slice',
	'some',
	'sort',
	'trim'
]);

/** Index a function by stable API/control-flow evidence before any similarity comparison. */
function overlapProfile(body) {
	const calls = new Map();
	const controls = new Map();
	const visit = (node, root) => {
		if (node !== root && ts.isFunctionLike(node)) return;
		if (ts.isCallExpression(node) || ts.isNewExpression(node)) {
			const callee = node.expression;
			const name = ts.isIdentifier(callee)
				? callee.text
				: ts.isPropertyAccessExpression(callee)
					? callee.name.text
					: ts.isElementAccessExpression(callee) && ts.isStringLiteral(callee.argumentExpression)
						? callee.argumentExpression.text
						: null;
			if (name && !GENERIC_CALLS.has(name)) calls.set(name, (calls.get(name) ?? 0) + 1);
		}
		const control =
			ts.isIfStatement(node) || ts.isConditionalExpression(node)
				? 'if'
				: ts.isForStatement(node) || ts.isForInStatement(node) || ts.isForOfStatement(node)
					? 'for'
					: ts.isWhileStatement(node) || ts.isDoStatement(node)
						? 'while'
						: ts.isSwitchStatement(node)
							? 'switch'
							: ts.isTryStatement(node)
								? 'try'
								: null;
		if (control) controls.set(control, (controls.get(control) ?? 0) + 1);
		ts.forEachChild(node, (child) => visit(child, root));
	};
	visit(body, body);
	if (calls.size < 2) return undefined;
	const encode = (entries) =>
		[...entries]
			.sort(([left], [right]) => left.localeCompare(right))
			.map(([key, count]) => `${key}:${count}`)
			.join(',');
	return { overlapBucket: `${encode(calls)}|${encode(controls)}` };
}

function shingleSimilarity(left, right) {
	let leftIndex = 0;
	let rightIndex = 0;
	let intersection = 0;
	while (leftIndex < left.length && rightIndex < right.length) {
		const order = left[leftIndex].localeCompare(right[rightIndex]);
		if (order === 0) {
			intersection += 1;
			leftIndex += 1;
			rightIndex += 1;
		} else if (order < 0) leftIndex += 1;
		else rightIndex += 1;
	}
	return intersection / Math.max(left.length + right.length - intersection, 1);
}

/** Identify a wrapper whose entire behavior is forwarding one call. */
function isPassThrough(body) {
	if (!ts.isBlock(body))
		return (
			ts.isCallExpression(body) ||
			(ts.isAwaitExpression(body) && ts.isCallExpression(body.expression))
		);
	if (body.statements.length !== 1) return false;
	const statement = body.statements[0];
	if (ts.isReturnStatement(statement) && statement.expression) {
		const expression = ts.isAwaitExpression(statement.expression)
			? statement.expression.expression
			: statement.expression;
		return ts.isCallExpression(expression);
	}
	if (ts.isExpressionStatement(statement)) {
		const expression = ts.isAwaitExpression(statement.expression)
			? statement.expression.expression
			: statement.expression;
		return ts.isCallExpression(expression);
	}
	return false;
}

function hasModifier(node, kind) {
	return node.modifiers?.some((modifier) => modifier.kind === kind) === true;
}

function topLevelFunctionCandidate(node) {
	if (ts.isFunctionDeclaration(node) && node.name && node.body && ts.isSourceFile(node.parent)) {
		return { node, name: node.name.text, nameNode: node.name, body: node.body };
	}
	if (
		ts.isVariableDeclaration(node) &&
		ts.isIdentifier(node.name) &&
		node.initializer &&
		(ts.isArrowFunction(node.initializer) || ts.isFunctionExpression(node.initializer)) &&
		ts.isVariableDeclarationList(node.parent) &&
		ts.isVariableStatement(node.parent.parent) &&
		ts.isSourceFile(node.parent.parent.parent)
	) {
		return {
			node: node.initializer,
			name: node.name.text,
			nameNode: node.name,
			body: node.initializer.body
		};
	}
	return null;
}

function isExportedTopLevelFunction(candidate) {
	const declaration = candidate.nameNode.parent;
	if (ts.isFunctionDeclaration(declaration))
		return (
			hasModifier(declaration, ts.SyntaxKind.ExportKeyword) ||
			hasModifier(declaration, ts.SyntaxKind.DefaultKeyword)
		);
	const statement = declaration.parent?.parent;
	return ts.isVariableStatement(statement) && hasModifier(statement, ts.SyntaxKind.ExportKeyword);
}

function directReturnedExpression(body) {
	if (!ts.isBlock(body)) return body;
	if (body.statements.length !== 1) return null;
	const statement = body.statements[0];
	return ts.isReturnStatement(statement) && statement.expression ? statement.expression : null;
}

function transparentForwardedCall(candidate) {
	if (candidate.node.modifiers?.some(({ kind }) => kind === ts.SyntaxKind.AsyncKeyword))
		return null;
	if (candidate.node.asteriskToken) return null;
	const parameters = candidate.node.parameters.map((parameter) =>
		ts.isIdentifier(parameter.name) && !parameter.initializer && !parameter.dotDotDotToken
			? parameter.name.text
			: null
	);
	if (parameters.some((name) => name === null)) return null;
	const returned = directReturnedExpression(candidate.body);
	const call = returned && ts.isCallExpression(returned) ? returned : null;
	if (!call || call.arguments.length !== parameters.length) return null;
	if (
		!call.arguments.every(
			(argument, index) => ts.isIdentifier(argument) && argument.text === parameters[index]
		)
	)
		return null;
	return call.expression.getText(candidate.nameNode.getSourceFile());
}

function tokenCount(text) {
	const scanner = ts.createScanner(ts.ScriptTarget.Latest, true, ts.LanguageVariant.Standard, text);
	let count = 0;
	for (let token = scanner.scan(); token !== ts.SyntaxKind.EndOfFileToken; token = scanner.scan())
		count += 1;
	return count;
}

function isValueIdentifier(node) {
	const parent = node.parent;
	if (!parent) return false;
	if (
		(ts.isFunctionDeclaration(parent) ||
			ts.isFunctionExpression(parent) ||
			ts.isClassDeclaration(parent) ||
			ts.isClassExpression(parent) ||
			ts.isMethodDeclaration(parent) ||
			ts.isPropertyDeclaration(parent) ||
			ts.isVariableDeclaration(parent) ||
			ts.isParameter(parent) ||
			ts.isTypeAliasDeclaration(parent) ||
			ts.isInterfaceDeclaration(parent)) &&
		parent.name === node
	)
		return false;
	if (
		ts.isImportSpecifier(parent) ||
		ts.isImportClause(parent) ||
		ts.isNamespaceImport(parent) ||
		ts.isExportSpecifier(parent) ||
		ts.isTypeReferenceNode(parent) ||
		ts.isQualifiedName(parent) ||
		ts.isLiteralTypeNode(parent) ||
		(ts.isPropertyAccessExpression(parent) && parent.name === node) ||
		((ts.isPropertyAssignment(parent) || ts.isPropertySignature(parent)) && parent.name === node)
	)
		return false;
	return true;
}

function safeSingleExpression(candidate) {
	if (candidate.node.modifiers?.some(({ kind }) => kind === ts.SyntaxKind.AsyncKeyword))
		return null;
	if (candidate.node.asteriskToken || candidate.node.typeParameters?.length) return null;
	if (
		candidate.node.parameters.some(
			(parameter) =>
				!ts.isIdentifier(parameter.name) || parameter.initializer || parameter.dotDotDotToken
		)
	)
		return null;
	const expression = directReturnedExpression(candidate.body);
	if (!expression || tokenCount(expression.getText(candidate.nameNode.getSourceFile())) > 24)
		return null;
	let unsafe = false;
	const visit = (node) => {
		if (
			node.kind === ts.SyntaxKind.ThisKeyword ||
			node.kind === ts.SyntaxKind.SuperKeyword ||
			ts.isAwaitExpression(node) ||
			ts.isYieldExpression(node) ||
			ts.isConditionalExpression(node) ||
			ts.isFunctionLike(node) ||
			ts.isClassExpression(node) ||
			(ts.isBinaryExpression(node) &&
				node.operatorToken.kind >= ts.SyntaxKind.FirstAssignment &&
				node.operatorToken.kind <= ts.SyntaxKind.LastAssignment) ||
			(ts.isPrefixUnaryExpression(node) &&
				[ts.SyntaxKind.PlusPlusToken, ts.SyntaxKind.MinusMinusToken].includes(node.operator)) ||
			ts.isPostfixUnaryExpression(node)
		) {
			unsafe = true;
			return;
		}
		ts.forEachChild(node, visit);
	};
	visit(expression);
	return unsafe ? null : expression;
}

/** Find only mechanically inlineable same-file one-use functions; larger abstractions stay inventory. */
function inlineEvidence(file, candidates) {
	const counts = new Map();
	for (const candidate of candidates)
		counts.set(candidate.name, (counts.get(candidate.name) ?? 0) + 1);
	const references = new Map(candidates.map(({ name }) => [name, []]));
	const visit = (node) => {
		if (ts.isIdentifier(node) && references.has(node.text) && isValueIdentifier(node))
			references.get(node.text).push(node);
		ts.forEachChild(node, visit);
	};
	visit(file);
	const localCalls = [...references.values()].reduce(
		(total, uses) =>
			total +
			uses.filter((use) => ts.isCallExpression(use.parent) && use.parent.expression === use).length,
		0
	);
	const inlineCandidates = [];
	for (const candidate of candidates) {
		if (counts.get(candidate.name) !== 1 || isExportedTopLevelFunction(candidate)) continue;
		const uses = references.get(candidate.name);
		const externalUses = uses.filter(
			(use) => use.getStart(file) < candidate.node.getStart(file) || use.end > candidate.node.end
		);
		if (
			externalUses.length !== 1 ||
			!ts.isCallExpression(externalUses[0].parent) ||
			externalUses[0].parent.expression !== externalUses[0]
		)
			continue;
		const forwardedTo = transparentForwardedCall(candidate);
		const expression = forwardedTo ? null : safeSingleExpression(candidate);
		if (!forwardedTo && !expression) continue;
		inlineCandidates.push({
			name: candidate.name,
			line: file.getLineAndCharacterOfPosition(candidate.nameNode.getStart(file)).line + 1,
			useLine: file.getLineAndCharacterOfPosition(externalUses[0].getStart(file)).line + 1,
			kind: forwardedTo ? 'transparent-forwarder' : 'single-use-expression',
			confidence: forwardedTo ? 'high' : 'review',
			...(forwardedTo ? { forwardsTo: forwardedTo } : {}),
			tokens: tokenCount(candidate.body.getText(file))
		});
	}
	return { inlineCandidates, localCalls };
}

/** Extract imports, functions, and Effect-style service ownership from the compiler AST. */
function analyzeAst(path, source) {
	const scriptKind = path.endsWith('.tsx')
		? ts.ScriptKind.TSX
		: path.endsWith('.jsx')
			? ts.ScriptKind.JSX
			: path.endsWith('.js') || path.endsWith('.mjs') || path.endsWith('.cjs')
				? ts.ScriptKind.JS
				: ts.ScriptKind.TS;
	const file = ts.createSourceFile(
		path,
		analyzableSource(path, source),
		ts.ScriptTarget.Latest,
		true,
		scriptKind
	);
	const imports = [];
	const functions = [];
	const duplicateEntities = [];
	const services = [];
	const topLevelFunctions = [];
	const visit = (node) => {
		const topLevel = topLevelFunctionCandidate(node);
		if (topLevel) topLevelFunctions.push(topLevel);
		if (ts.isImportDeclaration(node) && ts.isStringLiteral(node.moduleSpecifier))
			imports.push({
				specifier: node.moduleSpecifier.text,
				typeOnly:
					node.importClause?.isTypeOnly === true ||
					(node.importClause?.name === undefined &&
						node.importClause?.namedBindings !== undefined &&
						ts.isNamedImports(node.importClause.namedBindings) &&
						node.importClause.namedBindings.elements.every((item) => item.isTypeOnly))
			});
		if (
			ts.isExportDeclaration(node) &&
			node.moduleSpecifier &&
			ts.isStringLiteral(node.moduleSpecifier)
		)
			imports.push({
				specifier: node.moduleSpecifier.text,
				typeOnly:
					node.isTypeOnly ||
					(node.exportClause !== undefined &&
						ts.isNamedExports(node.exportClause) &&
						node.exportClause.elements.every((item) => item.isTypeOnly))
			});
		if (
			ts.isCallExpression(node) &&
			node.expression.kind === ts.SyntaxKind.ImportKeyword &&
			node.arguments.length === 1 &&
			ts.isStringLiteral(node.arguments[0])
		)
			imports.push({ specifier: node.arguments[0].text, typeOnly: false });
		if (
			ts.isCallExpression(node) &&
			ts.isIdentifier(node.expression) &&
			node.expression.text === 'require' &&
			node.arguments.length === 1 &&
			ts.isStringLiteral(node.arguments[0])
		)
			imports.push({ specifier: node.arguments[0].text, typeOnly: false });
		if (
			ts.isNewExpression(node) &&
			ts.isIdentifier(node.expression) &&
			node.expression.text === 'URL' &&
			node.arguments?.length === 2 &&
			ts.isStringLiteral(node.arguments[0]) &&
			node.arguments[1].getText(file) === 'import.meta.url'
		)
			imports.push({ specifier: node.arguments[0].text, typeOnly: false });
		const functionLike =
			(ts.isFunctionDeclaration(node) ||
				ts.isMethodDeclaration(node) ||
				ts.isConstructorDeclaration(node) ||
				ts.isGetAccessorDeclaration(node) ||
				ts.isSetAccessorDeclaration(node) ||
				ts.isArrowFunction(node) ||
				ts.isFunctionExpression(node)) &&
			node.body;
		if (functionLike) {
			const metrics = complexityOf(node.body);
			functions.push({
				name: declarationName(node),
				line: file.getLineAndCharacterOfPosition(node.getStart(file)).line + 1,
				...metrics,
				passThrough: isPassThrough(node.body)
			});
			const kind = duplicateCallableKind(node);
			const pathway = kind ? pathwayHash(node.body.getText(file)) : undefined;
			if (pathway) {
				const owner = containingClass(node);
				duplicateEntities.push({
					name: duplicateCallableName(node, file),
					kind,
					ownerClassId: owner ? `${path}:${owner.getStart(file)}` : null,
					line: file.getLineAndCharacterOfPosition(node.getStart(file)).line + 1,
					...metrics,
					passThrough: isPassThrough(node.body),
					...pathway,
					...(overlapProfile(node.body) ?? {})
				});
			}
		}
		if (ts.isClassDeclaration(node) || ts.isClassExpression(node)) {
			const pathway = classPathway(node, file);
			if (pathway) {
				duplicateEntities.push({
					name: className(node, file),
					kind: 'class',
					ownerClassId: `${path}:${node.getStart(file)}`,
					line: file.getLineAndCharacterOfPosition(node.getStart(file)).line + 1,
					...directClassComplexity(node),
					passThrough: false,
					...pathway
				});
			}
		}
		if (
			ts.isClassDeclaration(node) &&
			node.name &&
			node.heritageClauses?.some((clause) =>
				clause.getText(file).match(/(?:Effect|Context|ServiceMap)\.Service/)
			)
		)
			services.push(node.name.text);
		if (
			ts.isVariableDeclaration(node) &&
			ts.isIdentifier(node.name) &&
			node.initializer &&
			/(?:Context|ServiceMap)\.(?:(?:Generic)?Tag|Service)\s*(?:<[^;]+?>)?\s*\(/.test(
				node.initializer.getText(file)
			)
		)
			services.push(node.name.text);
		ts.forEachChild(node, visit);
	};
	visit(file);
	const indirection = inlineEvidence(file, topLevelFunctions);
	return {
		imports: [
			...new Map(
				imports.map((item) => [`${item.typeOnly ? 'type' : 'value'}:${item.specifier}`, item])
			).values()
		].sort(
			(a, b) => a.specifier.localeCompare(b.specifier) || Number(a.typeOnly) - Number(b.typeOnly)
		),
		functions,
		namedFunctions: topLevelFunctions.length,
		namedPassThroughFunctions: topLevelFunctions.filter(({ body }) => isPassThrough(body)).length,
		inlineCandidates: indirection.inlineCandidates,
		localNamedCalls: indirection.localCalls,
		duplicateEntities,
		services: [...new Set(services)].sort()
	};
}

/** Resolve one possible stem through runtime extensions and source index files. */
function resolveStem(stem, fileSet) {
	const clean = stem.replace(/[?#].*$/, '');
	const extension = extname(clean);
	const withoutRuntimeExtension = ['.js', '.jsx', '.mjs', '.cjs'].includes(extension)
		? clean.slice(0, -extension.length)
		: clean;
	const candidates = [
		clean,
		withoutRuntimeExtension,
		...[...SOURCE_EXTENSIONS].map((item) => `${withoutRuntimeExtension}${item}`),
		...[...SOURCE_EXTENSIONS].map((item) => join(withoutRuntimeExtension, `index${item}`))
	];
	return candidates.find((candidate) => fileSet.has(candidate));
}

/** Resolve a source specifier and distinguish unresolved internal edges from external packages. */
function resolveImport(from, specifier, fileSet, packageByName, owner, aliasesByRoot) {
	let stems = [];
	let internal = false;
	if (specifier.startsWith('./') || specifier.startsWith('../')) {
		internal = true;
		stems = [resolve(dirname(from), specifier)];
	} else {
		for (const mapping of aliasesByRoot.get(owner.root) ?? []) {
			const mapped = mappedStems(specifier, mapping);
			if (mapped.length === 0) continue;
			internal = true;
			stems = mapped;
			break;
		}
	}
	// `#lib/` is not a convention — it is whatever the manifest's `imports` map says, which
	// `moduleMappings` now reads. `$lib/` really is SvelteKit's fixed convention, so it stays.
	if (stems.length === 0 && specifier.startsWith('#')) internal = true;
	if (stems.length === 0 && specifier.startsWith('$lib/')) {
		internal = true;
		stems = [join(owner.root, 'src', 'lib', specifier.slice(5))];
	}
	if (stems.length === 0) {
		const matched = [...packageByName.keys()]
			.sort((a, b) => b.length - a.length || a.localeCompare(b))
			.find((name) => specifier === name || specifier.startsWith(`${name}/`));
		if (matched) {
			internal = true;
			const owners = packageByName.get(matched);
			const localOwners = owners.filter((candidate) => candidate.scanRoot === owner.scanRoot);
			const candidates = localOwners.length > 0 ? localOwners : owners;
			if (candidates.length !== 1)
				throw new Error(
					`ambiguous workspace package name ${matched}: ${candidates.map((item) => item.id).join(', ')}`
				);
			const target = candidates[0];
			const subpath = specifier === matched ? '' : specifier.slice(matched.length + 1);
			stems = exportedStems(target, subpath);
			if (stems.length === 0) stems = [join(target.root, 'src', subpath || 'index')];
		}
	}
	const targets = [
		...new Set(stems.map((stem) => resolveStem(stem, fileSet)).filter((item) => item !== undefined))
	].sort();
	return { targets, internal };
}

/** Whether a path belongs to the scanner's complete production source inventory. */
function scannerExcluded(root, file) {
	return (
		ignoredFile(root, file) ||
		/\.d\.(?:ts|mts|cts)$/.test(file) ||
		/(?:^|\/)[^/]+\.(?:generated|gen)(?:\.svelte)?\.(?:[cm]?[jt]sx?|svelte)$/.test(file) ||
		/(^|\/)(node_modules|\.yalc|build|dist|coverage|generated|\.generated|\.svelte-check|\.svelte-kit(?:-e2e)?|\.tmp|\.data|\.agents|\.opencode)(\/|$)/.test(
			file
		) ||
		/(^|\/)(test|tests|e2e|__tests__)(\/|$)/.test(file) ||
		/\.(test|spec)\.[^.]+$/.test(file) ||
		hasGeneratedHeader(join(root, file))
	);
}

/** Recompute the scanner input inventory exactly, including manifests and compiler configuration. */
function scannerInputInventory(root) {
	let discovered;
	let git = false;
	try {
		execFileSync('git', ['rev-parse', '--is-inside-work-tree'], { cwd: root, stdio: 'ignore' });
		git = true;
	} catch {
		/* rg is the deterministic fallback outside git */
	}
	if (git) {
		const patterns = [...SCANNER_SOURCE_EXTENSIONS].map((extension) => `*${extension}`);
		const tracked = execFileSync('git', ['ls-files', '-z', '--', ...patterns], {
			cwd: root,
			encoding: 'utf8'
		});
		const untracked = execFileSync(
			'git',
			['ls-files', '--others', '--exclude-standard', '-z', '--', ...patterns],
			{ cwd: root, encoding: 'utf8' }
		);
		discovered = `${tracked}${untracked}`.split('\0');
	} else {
		const globs = [...SCANNER_SOURCE_EXTENSIONS].flatMap((extension) => ['-g', `*${extension}`]);
		try {
			discovered = execFileSync('rg', ['--files', '-0', ...globs], {
				cwd: root,
				encoding: 'utf8'
			}).split('\0');
		} catch (error) {
			if (error?.status !== 1) throw error;
			discovered = [];
		}
	}
	const sources = [...new Set(discovered)]
		.filter(Boolean)
		.map((file) => file.split(sep).join('/'))
		.filter((file) => existsSync(join(root, file)) && !scannerExcluded(root, file))
		.sort();
	const inputs = new Set(sources);
	if (existsSync(join(root, '.doctorignore'))) inputs.add('.doctorignore');
	for (const file of sources) {
		let directory = dirname(join(root, file));
		while (directory === root || directory.startsWith(`${root}${sep}`)) {
			for (const name of ['package.json', 'tsconfig.json', 'jsconfig.json']) {
				const candidate = join(directory, name);
				if (existsSync(candidate)) inputs.add(relative(root, candidate).split(sep).join('/'));
			}
			if (directory === root) break;
			directory = dirname(directory);
		}
	}
	const digest = createHash('sha256');
	for (const file of [...inputs].sort()) {
		const bytes = readFileSync(join(root, file));
		const fileDigest = createHash('sha256').update(bytes).digest('hex');
		digest.update(`${file}\0${fileDigest}\n`, 'utf8');
	}
	return { sources, inputs: [...inputs].sort(), digest: `sha256:${digest.digest('hex')}` };
}

/** Validate one complete scanner receipt for every selected root before accepting its catalogue. */
function scannerCatalogues(receiptPaths, roots) {
	if (receiptPaths.length !== roots.length)
		throw new Error(
			`expected one scanner receipt per root (${roots.length}), received ${receiptPaths.length}`
		);
	const byRoot = new Map();
	for (const receiptPath of receiptPaths) {
		const receipt = JSON.parse(readFileSync(receiptPath, 'utf8'));
		const fields = [
			'catalogueDigest',
			'complete',
			'counts',
			'files',
			'findings',
			'includeTests',
			'kind',
			'root',
			'ruleSetDigest',
			'scannerVersion',
			'schemaVersion',
			'scope',
			'sourceInventoryDigest',
			'tiers'
		];
		if (JSON.stringify(Object.keys(receipt).sort()) !== JSON.stringify(fields))
			throw new Error(`scanner receipt fields do not match schema: ${receiptPath}`);
		if (
			receipt.schemaVersion !== RECEIPT_SCHEMA_VERSION ||
			receipt.kind !== 'repository-health-static-receipt' ||
			receipt.scannerVersion !== SCANNER_VERSION
		)
			throw new Error(`unsupported scanner receipt: ${receiptPath}`);
		const tiers = receipt.tiers;
		if (
			typeof tiers !== 'object' ||
			tiers === null ||
			tiers.syntactic !== true ||
			typeof tiers.graph !== 'boolean' ||
			typeof tiers.typeAware !== 'boolean'
		)
			throw new Error(`scanner receipt does not record tier coverage: ${receiptPath}`);
		if (
			receipt.scope !== 'all' ||
			receipt.includeTests !== false ||
			receipt.complete !== true ||
			receipt.findings !== 'findings.tsv'
		)
			throw new Error(`scanner receipt is not a complete production scan: ${receiptPath}`);
		const root = realpathSync(receipt.root);
		if (receipt.root !== root)
			throw new Error(`scanner receipt root is not canonical: ${receiptPath}`);
		if (!roots.includes(root)) throw new Error(`scanner receipt root was not selected: ${root}`);
		if (byRoot.has(root)) throw new Error(`duplicate scanner receipt for root: ${root}`);
		if (receiptPath !== join(root, '.norbital/diagnosis/receipt.json'))
			throw new Error(`scanner receipt is not at the canonical root path: ${receiptPath}`);
		if (!Number.isSafeInteger(receipt.files) || receipt.files < 0)
			throw new Error(`invalid scanner source count: ${receiptPath}`);
		const catalogue = join(dirname(receiptPath), receipt.findings);
		if (!existsSync(catalogue)) throw new Error(`scanner catalogue does not exist: ${catalogue}`);
		const inventory = scannerInputInventory(root);
		if (receipt.files !== inventory.sources.length)
			throw new Error(`scanner source count is stale for root: ${root}`);
		if (receipt.sourceInventoryDigest !== inventory.digest)
			throw new Error(`scanner input inventory is stale for root: ${root}`);
		for (const [name, value] of [
			['sourceInventoryDigest', receipt.sourceInventoryDigest],
			['ruleSetDigest', receipt.ruleSetDigest],
			['catalogueDigest', receipt.catalogueDigest]
		])
			if (typeof value !== 'string' || !/^sha256:[0-9a-f]{64}$/.test(value))
				throw new Error(`invalid scanner ${name}: ${receiptPath}`);
		const catalogueBytes = readFileSync(catalogue);
		const catalogueDigest = `sha256:${createHash('sha256').update(catalogueBytes).digest('hex')}`;
		if (receipt.catalogueDigest !== catalogueDigest)
			throw new Error(`scanner catalogue digest mismatch: ${catalogue}`);
		const rows = catalogueBytes.toString('utf8').split(/\r?\n/).filter(Boolean);
		const counts = {
			error: 0,
			warning: 0,
			hint: 0,
			total: rows.length,
			principles: emptyPrincipleCounts()
		};
		for (const line of rows) {
			const columns = line.split('\t');
			if (columns.length !== 6) throw new Error(`invalid scanner catalogue row: ${catalogue}`);
			const [severity, , , , , encodedPrinciples] = columns;
			if (!['error', 'warning', 'hint'].includes(severity))
				throw new Error(`invalid scanner severity in ${catalogue}`);
			counts[severity] += 1;
			const principles = (encodedPrinciples ?? '').split(',').filter(Boolean);
			const canonical = PRINCIPLES.filter((principle) => principles.includes(principle));
			if (
				canonical.length === 0 ||
				canonical.length !== principles.length ||
				canonical.some((principle, index) => principle !== principles[index])
			)
				throw new Error(`invalid scanner principle bucket in ${catalogue}`);
			for (const principle of canonical) {
				const key = principleCountKey(principle);
				counts.principles[key] += 1;
			}
		}
		if (
			!receipt.counts ||
			JSON.stringify(Object.keys(receipt.counts).sort()) !==
				JSON.stringify(['error', 'hint', 'principles', 'total', 'warning']) ||
			JSON.stringify(Object.keys(receipt.counts.principles ?? {}).sort()) !==
				JSON.stringify(PRINCIPLE_COUNT_KEYS) ||
			Object.entries(counts)
				.filter(([name]) => name !== 'principles')
				.some(([name, value]) => receipt.counts[name] !== value) ||
			Object.entries(counts.principles).some(
				([name, value]) => receipt.counts.principles?.[name] !== value
			)
		)
			throw new Error(`scanner finding counts mismatch: ${catalogue}`);
		byRoot.set(root, { receiptPath, receipt, catalogue, rows, inventory });
	}
	return roots.map((root) => byRoot.get(root));
}

/** Import verified scanner catalogues and attach each static violation to its owning concept. */
function staticFindings(catalogues, byPath, rootByPath) {
	const rows = [];
	for (const { receiptPath, receipt, rows: catalogueRows } of catalogues) {
		const root = receipt.root;
		const rootId = rootByPath.get(root).id;
		for (const line of catalogueRows) {
			const [severity, confidence, rule, summary, location, encodedPrinciples] = line.split('\t');
			if (!['error', 'warning', 'hint'].includes(severity) || !rule || !location)
				throw new Error(`invalid findings row in ${receiptPath}`);
			const match = location.match(/^(.+?):(\d+)(?::\d+)?:(?:\s|$)/);
			const evidence = location.match(/\[([^\]]+)\]\s*$/)?.[1] ?? null;
			const absolute = match ? resolve(root, match[1]) : undefined;
			const record = absolute ? byPath.get(absolute) : undefined;
			const principles = PRINCIPLES.filter((principle) =>
				(encodedPrinciples ?? '').split(',').includes(principle)
			);
			rows.push({
				severity,
				confidence,
				rule,
				summary,
				location,
				line: match ? Number(match[2]) : null,
				evidence,
				principles,
				file: record?.displayPath ?? (match ? `${rootId}/${match[1]}` : null),
				concept: record?.concept ?? 'unmapped'
			});
		}
	}
	const countBy = (key) =>
		[...rows.reduce((map, row) => map.set(row[key], (map.get(row[key]) ?? 0) + 1), new Map())]
			.map(([name, count]) => ({ name, count }))
			.sort((a, b) => b.count - a.count || a.name.localeCompare(b.name));
	const totals = {
		error: rows.filter((row) => row.severity === 'error').length,
		warning: rows.filter((row) => row.severity === 'warning').length,
		hint: rows.filter((row) => row.severity === 'hint').length
	};
	const byPrinciple = PRINCIPLES.map((principle) => ({
		name: principle,
		count: rows.filter((row) => row.principles.includes(principle)).length
	}));
	return {
		catalogues: catalogues.map(({ receiptPath, receipt }) => ({
			root: rootByPath.get(receipt.root).id,
			receipt: receiptPath,
			sourceInventoryDigest: receipt.sourceInventoryDigest,
			ruleSetDigest: receipt.ruleSetDigest,
			catalogueDigest: receipt.catalogueDigest
		})),
		totals,
		byRule: countBy('rule'),
		byPrinciple,
		byConcept: countBy('concept'),
		findings: rows
	};
}

/** Calculate deterministic descriptive statistics over a finite metric population. */
function distribution(values) {
	const sorted = [...values].sort((a, b) => a - b);
	if (sorted.length === 0)
		return { count: 0, mean: 0, stdev: 0, cv: 0, gini: 0, median: 0, p90: 0, p95: 0, max: 0 };
	const sum = sorted.reduce((total, value) => total + value, 0);
	const mean = sum / sorted.length;
	const stdev = Math.sqrt(
		sorted.reduce((total, value) => total + (value - mean) ** 2, 0) / sorted.length
	);
	const percentile = (fraction) => sorted[Math.max(0, Math.ceil(fraction * sorted.length) - 1)];
	const weighted = sorted.reduce((total, value, index) => total + (index + 1) * value, 0);
	const gini =
		sum === 0 ? 0 : (2 * weighted) / (sorted.length * sum) - (sorted.length + 1) / sorted.length;
	const rounded = (value) => Math.round(value * 1000) / 1000;
	return {
		count: sorted.length,
		mean: rounded(mean),
		stdev: rounded(stdev),
		cv: rounded(mean === 0 ? 0 : stdev / mean),
		gini: rounded(gini),
		median: percentile(0.5),
		p90: percentile(0.9),
		p95: percentile(0.95),
		max: sorted.at(-1)
	};
}

/** Find strongly connected components using a stable Tarjan traversal. */
function stronglyConnected(nodes, adjacency) {
	let index = 0;
	const stack = [];
	const onStack = new Set();
	const indices = new Map();
	const low = new Map();
	const components = [];
	const connect = (node) => {
		indices.set(node, index);
		low.set(node, index);
		index += 1;
		stack.push(node);
		onStack.add(node);
		for (const target of [...(adjacency.get(node) ?? [])].sort()) {
			if (!indices.has(target)) {
				connect(target);
				low.set(node, Math.min(low.get(node), low.get(target)));
			} else if (onStack.has(target)) low.set(node, Math.min(low.get(node), indices.get(target)));
		}
		if (low.get(node) === indices.get(node)) {
			const component = [];
			let current;
			do {
				current = stack.pop();
				onStack.delete(current);
				component.push(current);
			} while (current !== node);
			components.push(component.sort());
		}
	};
	for (const node of [...nodes].sort()) if (!indices.has(node)) connect(node);
	return components
		.filter(
			(component) => component.length > 1 || adjacency.get(component[0])?.has(component[0]) === true
		)
		.sort((a, b) => a[0].localeCompare(b[0]));
}

/** Follow production dependencies reachable from every test module. */
function testReach(testFiles, adjacency, productionSet) {
	const reached = new Set();
	const queue = [...testFiles].sort();
	const seen = new Set(queue);
	while (queue.length > 0) {
		const current = queue.shift();
		for (const target of [...(adjacency.get(current) ?? [])].sort()) {
			if (productionSet.has(target)) reached.add(target);
			if (!seen.has(target)) {
				seen.add(target);
				queue.push(target);
			}
		}
	}
	return reached;
}

/** Give roots collision-safe report identities without depending on argument order. */
function describeRoots(roots) {
	const counts = new Map();
	for (const root of roots) counts.set(basename(root), (counts.get(basename(root)) ?? 0) + 1);
	return roots.map((path) => ({
		path,
		id:
			counts.get(basename(path)) === 1
				? basename(path)
				: `${basename(path)}-${createHash('sha256').update(path).digest('hex').slice(0, 8)}`
	}));
}

/** Build exact and high-confidence near-duplicate evidence for named code entities. */
function pathwayEvidence(entities) {
	const exactBuckets = new Map();
	for (const item of entities)
		if (item.hash) {
			const family = item.kind === 'class' ? 'class' : 'callable';
			const key = `${item.rootId}\0${family}\0${item.hash}`;
			const group = exactBuckets.get(key) ?? [];
			group.push(item);
			exactBuckets.set(key, group);
		}
	const duplicatedClassOwners = new Set(
		[...exactBuckets.values()]
			.filter(
				(group) => group[0]?.kind === 'class' && new Set(group.map((item) => item.file)).size > 1
			)
			.flatMap((group) => group.map(({ ownerClassId }) => ownerClassId))
	);
	const eligible = entities.filter(
		(item) => !(item.kind === 'method' && duplicatedClassOwners.has(item.ownerClassId))
	);
	const occurrence = (item) => ({
		id: createHash('sha256')
			.update(`${item.rootId}\0${item.file}\0${item.line}\0${item.kind}\0${item.name}`)
			.digest('hex')
			.slice(0, 16),
		file: item.file,
		entity: item.name,
		kind: item.kind,
		line: item.line,
		concept: item.concept,
		pillar: item.pillar,
		tokens: item.tokens,
		cyclomatic: item.cyclomatic,
		nesting: item.nesting,
		passThrough: item.passThrough === true,
		operationSignature: item.overlapBucket ?? null
	});
	const eligibleIds = new Set(
		eligible.map((item) => `${item.rootId}\0${item.file}\0${item.line}\0${item.kind}\0${item.name}`)
	);
	const exact = [...exactBuckets.entries()]
		.map(([key, group]) => [
			key,
			group.filter((item) =>
				eligibleIds.has(`${item.rootId}\0${item.file}\0${item.line}\0${item.kind}\0${item.name}`)
			)
		])
		.filter(([, group]) => new Set(group.map((item) => item.file)).size > 1)
		.map(([key, group]) => ({
			kind: group[0].kind === 'class' ? 'class' : 'callable',
			hash: key.split('\0').at(-1),
			occurrences: group
				.map(occurrence)
				.sort(
					(a, b) =>
						a.file.localeCompare(b.file) || a.line - b.line || a.entity.localeCompare(b.entity)
				)
		}))
		.sort((a, b) => a.hash.localeCompare(b.hash));

	const indexed = new Map();
	for (const item of eligible) {
		if (item.tokens < 60 || !item.overlapBucket || !item.shingles?.length) continue;
		const key = `${item.rootId}\0${item.overlapBucket}`;
		const group = indexed.get(key) ?? [];
		group.push(item);
		indexed.set(key, group);
	}
	const overlapping = [];
	for (const group of indexed.values()) {
		group.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line);
		for (let leftIndex = 0; leftIndex < group.length; leftIndex += 1)
			for (let rightIndex = leftIndex + 1; rightIndex < group.length; rightIndex += 1) {
				const left = group[leftIndex];
				const right = group[rightIndex];
				if (left.file === right.file || left.hash === right.hash) continue;
				const sizeRatio = Math.min(left.tokens, right.tokens) / Math.max(left.tokens, right.tokens);
				if (sizeRatio < 0.85) continue;
				const similarity = shingleSimilarity(left.shingles, right.shingles);
				if (similarity < 0.88) continue;
				overlapping.push({
					similarity: Math.round(similarity * 1_000_000) / 1_000_000,
					operationSignature: left.overlapBucket,
					left: occurrence(left),
					right: occurrence(right)
				});
			}
	}
	overlapping.sort(
		(a, b) =>
			b.similarity - a.similarity ||
			a.left.file.localeCompare(b.left.file) ||
			a.left.line - b.left.line ||
			a.right.file.localeCompare(b.right.file) ||
			a.right.line - b.right.line
	);
	return { exact, overlapping, clusters: clusterPathways(exact, overlapping) };
}

const GENERIC_LABEL_WORDS = new Set([
	'anonymous',
	'build',
	'calculate',
	'create',
	'from',
	'get',
	'handle',
	'load',
	'make',
	'of',
	'process',
	'run',
	'set',
	'to'
]);
const GENERIC_LABEL_CALLS = new Set([
	...GENERIC_CALLS,
	'Array',
	'Date',
	'Error',
	'Map',
	'Number',
	'Object',
	'Set',
	'String',
	'bind',
	'effect',
	'fn',
	'gen',
	'make',
	'of',
	'succeed',
	'success',
	't',
	'update'
]);

function operationCalls(signature) {
	if (!signature) return [];
	return signature
		.split('|', 1)[0]
		.split(',')
		.map((item) => item.match(/^(.+):(\d+)$/))
		.filter(Boolean)
		.map(([, name, count]) => [name, Number(count)])
		.filter(([name]) => !GENERIC_LABEL_CALLS.has(name));
}

/** Label one connected pathway family from stable API evidence, never embeddings or an LLM. */
function clusterLabel(members) {
	const calls = new Map();
	for (const member of members)
		for (const [name, count] of operationCalls(member.operationSignature))
			calls.set(name, (calls.get(name) ?? 0) + count);
	const rankedCalls = [...calls]
		.sort(
			([leftName, leftCount], [rightName, rightCount]) =>
				rightCount - leftCount || leftName.localeCompare(rightName)
		)
		.slice(0, 3)
		.map(([name]) => name);
	if (rankedCalls.length) return `calls: ${rankedCalls.join(' + ')}`;
	const words = new Map();
	for (const member of members)
		for (const word of member.entity
			.replace(/([a-z0-9])([A-Z])/g, '$1 $2')
			.split(/[^A-Za-z0-9]+/)
			.map((item) => item.toLowerCase())
			.filter((item) => item.length > 1 && !GENERIC_LABEL_WORDS.has(item)))
			words.set(word, (words.get(word) ?? 0) + 1);
	const rankedWords = [...words]
		.sort(
			([leftWord, leftCount], [rightWord, rightCount]) =>
				rightCount - leftCount || leftWord.localeCompare(rightWord)
		)
		.slice(0, 3)
		.map(([word]) => word);
	return rankedWords.length
		? `functions: ${rankedWords.join(' + ')}`
		: 'structurally duplicated pathway';
}

/** Collapse exact and near-duplicate relationships into deterministic functionality clusters. */
function clusterPathways(exact, overlapping) {
	const nodes = new Map();
	const parents = new Map();
	const exactEdges = new Map();
	const overlapEdges = new Map();
	const register = (occurrence) => {
		nodes.set(occurrence.id, occurrence);
		if (!parents.has(occurrence.id)) parents.set(occurrence.id, occurrence.id);
	};
	const find = (id) => {
		let root = id;
		while (parents.get(root) !== root) root = parents.get(root);
		while (parents.get(id) !== id) {
			const next = parents.get(id);
			parents.set(id, root);
			id = next;
		}
		return root;
	};
	const unite = (left, right) => {
		const leftRoot = find(left);
		const rightRoot = find(right);
		if (leftRoot === rightRoot) return;
		const [first, second] = [leftRoot, rightRoot].sort();
		parents.set(second, first);
	};
	const edgeKey = (left, right) => [left, right].sort().join('\0');
	for (const group of exact) {
		for (const occurrence of group.occurrences) register(occurrence);
		for (let left = 0; left < group.occurrences.length; left += 1)
			for (let right = left + 1; right < group.occurrences.length; right += 1) {
				const leftId = group.occurrences[left].id;
				const rightId = group.occurrences[right].id;
				exactEdges.set(edgeKey(leftId, rightId), { left: leftId, right: rightId });
				unite(leftId, rightId);
			}
	}
	for (const relationship of overlapping) {
		register(relationship.left);
		register(relationship.right);
		const key = edgeKey(relationship.left.id, relationship.right.id);
		overlapEdges.set(key, {
			left: relationship.left.id,
			right: relationship.right.id,
			similarity: relationship.similarity
		});
		unite(relationship.left.id, relationship.right.id);
	}
	const grouped = new Map();
	for (const [id, occurrence] of nodes) {
		const root = find(id);
		const members = grouped.get(root) ?? [];
		members.push(occurrence);
		grouped.set(root, members);
	}
	const clusters = [];
	for (const members of grouped.values()) {
		members.sort(
			(left, right) =>
				left.file.localeCompare(right.file) ||
				left.line - right.line ||
				left.entity.localeCompare(right.entity)
		);
		const memberIds = new Set(members.map(({ id }) => id));
		const ownedExact = [...exactEdges.values()].filter(
			(edge) => memberIds.has(edge.left) && memberIds.has(edge.right)
		);
		const ownedOverlaps = [...overlapEdges.values()].filter(
			(edge) => memberIds.has(edge.left) && memberIds.has(edge.right)
		);
		const relationshipCount = ownedExact.length + ownedOverlaps.length;
		const relationships = [...ownedExact, ...ownedOverlaps];
		const possibleRelationships = (members.length * (members.length - 1)) / 2;
		const similarities = ownedOverlaps.map(({ similarity }) => similarity);
		const concepts = [...new Set(members.map(({ concept }) => concept))].sort();
		const pillars = [...new Set(members.map(({ pillar }) => pillar))].sort();
		const operationSignatures = [
			...new Set(members.map(({ operationSignature }) => operationSignature).filter(Boolean))
		].sort();
		const identity = members
			.map(({ id }) => id)
			.sort()
			.join('\0');
		clusters.push({
			id: createHash('sha256').update(identity).digest('hex').slice(0, 12),
			label: clusterLabel(members),
			members,
			concepts,
			crossConcept: concepts.length > 1,
			pillars,
			crossPillar: pillars.length > 1,
			operationSignatures,
			exactRelationships: ownedExact.length,
			overlapRelationships: ownedOverlaps.length,
			overlapDensity:
				possibleRelationships === 0
					? 0
					: Math.round((relationshipCount / possibleRelationships) * 1_000_000) / 1_000_000,
			averageSimilarity:
				similarities.length === 0
					? null
					: Math.round(
							(similarities.reduce((sum, value) => sum + value, 0) / similarities.length) *
								1_000_000
						) / 1_000_000,
			complexity: {
				cyclomatic: distribution(members.map(({ cyclomatic }) => cyclomatic)),
				nesting: distribution(members.map(({ nesting }) => nesting)),
				excessCyclomatic: members.reduce(
					(sum, { cyclomatic }) => sum + Math.max(0, cyclomatic - 1),
					0
				),
				totalTokens: members.reduce((sum, { tokens }) => sum + tokens, 0)
			},
			colocation: {
				sameConceptRelationships: relationships.filter(
					({ left, right }) => nodes.get(left).concept === nodes.get(right).concept
				).length,
				samePillarRelationships: relationships.filter(
					({ left, right }) => nodes.get(left).pillar === nodes.get(right).pillar
				).length,
				samePillarShare: roundedRatio(
					relationships.filter(
						({ left, right }) => nodes.get(left).pillar === nodes.get(right).pillar
					).length,
					relationshipCount
				)
			},
			indirection: {
				passThroughMembers: members.filter(({ passThrough }) => passThrough).length,
				passThroughShare: roundedRatio(
					members.filter(({ passThrough }) => passThrough).length,
					members.length
				)
			}
		});
	}
	return clusters.sort(
		(left, right) =>
			right.members.length - left.members.length ||
			right.crossConcept - left.crossConcept ||
			left.label.localeCompare(right.label) ||
			left.id.localeCompare(right.id)
	);
}

/** Parse only named code entities and skip graph/LOC/receipt work for a fast overlap check. */
function analyzeOverlaps(roots) {
	const files = collectSourceFiles(roots).filter((path) => !isTestPath(path));
	if (files.length === 0) throw new Error('selected zero production source files');
	const rootDescriptions = describeRoots(roots);
	const rootByPath = new Map(rootDescriptions.map((root) => [root.path, root]));
	const packageCache = new Map();
	const entities = [];
	for (const path of files) {
		const containingRoot = [...roots]
			.filter((root) => path === root || path.startsWith(`${root}${sep}`))
			.sort((a, b) => b.length - a.length)[0];
		const root = rootByPath.get(containingRoot);
		const owner = packageFor(path, containingRoot, root.id, packageCache);
		const displayPath = `${root.id}/${relative(containingRoot, path).split(sep).join('/')}`;
		const concept = conceptFor(path, owner);
		const pillar = pillarFor(path, owner);
		for (const item of analyzeAst(path, readFileSync(path, 'utf8')).duplicateEntities)
			entities.push({ ...item, file: displayPath, concept, pillar, rootId: root.id });
	}
	const pathways = pathwayEvidence(entities);
	return {
		schemaVersion: SCHEMA_VERSION,
		analyzerVersion: ANALYZER_VERSION,
		mode: 'overlap-only',
		roots: rootDescriptions,
		verdict: pathways.exact.length || pathways.overlapping.length ? 'findings' : 'pass',
		totals: {
			productionFiles: files.length,
			codeEntities: entities.length,
			duplicatePathwayGroups: pathways.exact.length,
			duplicatePathwayOccurrences: pathways.exact.reduce(
				(sum, group) => sum + group.occurrences.length,
				0
			),
			overlappingPathwayPairs: pathways.overlapping.length,
			functionalityClusters: pathways.clusters.length,
			crossConceptFunctionalityClusters: pathways.clusters.filter(
				({ crossConcept }) => crossConcept
			).length,
			crossPillarFunctionalityClusters: pathways.clusters.filter(({ crossPillar }) => crossPillar)
				.length,
			clusteredEntityOccurrences: pathways.clusters.reduce(
				(sum, cluster) => sum + cluster.members.length,
				0
			)
		},
		duplicatePathways: pathways.exact,
		overlappingPathways: pathways.overlapping,
		functionalityClusters: pathways.clusters
	};
}

function overlapMarkdown(report) {
	const lines = [
		'# Functionality overlap',
		'',
		`Verdict: **${report.verdict}**.`,
		'',
		`Scanned ${report.totals.productionFiles} production files and ${report.totals.codeEntities} named functions, methods, constructors/accessors, and classes.`,
		`Exact duplicate groups: ${report.totals.duplicatePathwayGroups}. High-confidence overlapping pairs: ${report.totals.overlappingPathwayPairs}. Functionality clusters: ${report.totals.functionalityClusters}.`
	];
	if (report.functionalityClusters.length) {
		lines.push(
			'',
			'## Functionality clusters',
			'',
			'| Label | Members | Pillars | Complexity p95 | Excess complexity | Pass-through | Same-pillar | Density |',
			'| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |'
		);
		for (const cluster of report.functionalityClusters.slice(0, 30))
			lines.push(
				`| ${cluster.label} | ${cluster.members.length} | ${cluster.pillars.length} | ${cluster.complexity.cyclomatic.p95} | ${cluster.complexity.excessCyclomatic} | ${cluster.indirection.passThroughMembers} | ${(cluster.colocation.samePillarShare * 100).toFixed(1)}% | ${(cluster.overlapDensity * 100).toFixed(1)}% |`
			);
	}
	if (report.overlappingPathways.length) {
		lines.push(
			'',
			'## Overlapping functionality',
			'',
			'| Similarity | Left | Right |',
			'| ---: | --- | --- |'
		);
		for (const item of report.overlappingPathways.slice(0, 50))
			lines.push(
				`| ${(item.similarity * 100).toFixed(1)}% | ${item.left.file}:${item.left.line} (${item.left.entity}) | ${item.right.file}:${item.right.line} (${item.right.entity}) |`
			);
	}
	return lines.join('\n');
}

function roundedRatio(numerator, denominator, scale = 1) {
	return denominator === 0
		? 0
		: Math.round((scale * numerator * 1_000_000) / denominator) / 1_000_000;
}

/** Aggregate path-owned child concepts into deterministic domain pillars. */
function buildPillars(production, productionAdjacency, byPath, cycles, quality, inlineCandidates) {
	const map = new Map();
	const cycleModules = new Set(cycles.flat());
	for (const record of production) {
		const name = record.pillar.slice(record.owner.id.length + 1);
		const current = map.get(record.pillar) ?? {
			pillar: record.pillar,
			name,
			label: `${record.owner.name}:${name}`,
			package: record.owner.id,
			packageName: record.owner.name,
			files: [],
			concepts: new Set(),
			codeLoc: 0,
			services: 0,
			functions: [],
			namedFunctions: 0,
			codeEntities: 0,
			cyclicModules: 0,
			localNamedCalls: 0,
			inlineCandidates: [],
			internalEdges: 0,
			inboundEdges: 0,
			outboundEdges: 0,
			locality: emptyLocality()
		};
		current.files.push(record.displayPath);
		current.concepts.add(record.concept);
		current.codeLoc += record.lines.code;
		current.services += record.services.length;
		current.functions.push(...record.functions);
		current.namedFunctions += record.namedFunctions;
		current.codeEntities += record.duplicateEntities.length;
		current.cyclicModules += cycleModules.has(record.path) ? 1 : 0;
		current.localNamedCalls += record.localNamedCalls;
		map.set(record.pillar, current);
	}
	for (const candidate of inlineCandidates)
		if (map.has(candidate.pillar)) map.get(candidate.pillar).inlineCandidates.push(candidate);
	for (const [from, targets] of productionAdjacency) {
		const source = byPath.get(from);
		for (const targetPath of targets) {
			const target = byPath.get(targetPath);
			const sourcePillar = map.get(source.pillar);
			sourcePillar.locality[importLocality(source, target)] += 1;
			if (source.pillar === target.pillar) sourcePillar.internalEdges += 1;
			else {
				sourcePillar.outboundEdges += 1;
				map.get(target.pillar).inboundEdges += 1;
			}
		}
	}
	const findingCounts = new Map();
	for (const finding of quality?.findings ?? [])
		if (finding.file) findingCounts.set(finding.file, (findingCounts.get(finding.file) ?? 0) + 1);
	return [...map.values()]
		.map((pillar) => {
			const cyclomatic = pillar.functions.map(({ cyclomatic }) => cyclomatic);
			const nesting = pillar.functions.map(({ nesting }) => nesting);
			const excessCyclomatic = cyclomatic.reduce(
				(sum, complexity) => sum + Math.max(0, complexity - 1),
				0
			);
			const boundaryEdges = pillar.inboundEdges + pillar.outboundEdges;
			const inlineCandidates = pillar.inlineCandidates.sort(
				(left, right) =>
					left.file.localeCompare(right.file) ||
					left.line - right.line ||
					left.name.localeCompare(right.name)
			);
			return {
				id: createHash('sha256').update(pillar.pillar).digest('hex').slice(0, 12),
				pillar: pillar.pillar,
				name: pillar.name,
				label: pillar.label,
				package: pillar.package,
				packageName: pillar.packageName,
				files: pillar.files.sort(),
				concepts: [...pillar.concepts].sort(),
				codeLoc: pillar.codeLoc,
				services: pillar.services,
				functions: pillar.functions.length,
				namedFunctions: pillar.namedFunctions,
				codeEntities: pillar.codeEntities,
				cyclicModules: pillar.cyclicModules,
				complexity: {
					cyclomatic: distribution(cyclomatic),
					nesting: distribution(nesting),
					excessCyclomatic,
					excessPerThousandLoc: roundedRatio(excessCyclomatic, pillar.codeLoc, 1_000)
				},
				cohesion: roundedRatio(2 * pillar.internalEdges, 2 * pillar.internalEdges + boundaryEdges),
				edges: {
					internal: pillar.internalEdges,
					inbound: pillar.inboundEdges,
					outbound: pillar.outboundEdges,
					boundary: boundaryEdges
				},
				colocation: {
					sameFileNamedCalls: pillar.localNamedCalls,
					imports: pillar.locality,
					importScore: localityScore(pillar.locality)
				},
				indirection: {
					inlineCandidates: inlineCandidates.length,
					highConfidence: inlineCandidates.filter(({ confidence }) => confidence === 'high').length,
					review: inlineCandidates.filter(({ confidence }) => confidence === 'review').length,
					transparentForwarders: inlineCandidates.filter(
						({ kind }) => kind === 'transparent-forwarder'
					).length,
					callbackProxies: inlineCandidates.filter(({ kind }) => kind === 'callback-proxy').length,
					singleUseExpressions: inlineCandidates.filter(
						({ kind }) => kind === 'single-use-expression'
					).length,
					perHundredNamedFunctions: roundedRatio(
						inlineCandidates.length,
						pillar.namedFunctions,
						100
					),
					candidates: inlineCandidates
				},
				staticFindings: pillar.files.reduce((sum, file) => sum + (findingCounts.get(file) ?? 0), 0)
			};
		})
		.sort((left, right) => right.codeLoc - left.codeLoc || left.pillar.localeCompare(right.pillar));
}

/** Build the complete snapshot and its evidence tables from one immutable file inventory. */
function analyze(roots, receiptPaths = []) {
	const files = collectSourceFiles(roots);
	if (files.length === 0) throw new Error('selected zero source files');
	const rootDescriptions = describeRoots(roots);
	const rootByPath = new Map(rootDescriptions.map((root) => [root.path, root]));
	const packageCache = new Map();
	const records = files.map((path) => {
		const source = readFileSync(path, 'utf8');
		const containingRoot = [...roots]
			.filter((root) => path === root || path.startsWith(`${root}${sep}`))
			.sort((a, b) => b.length - a.length)[0];
		const root = rootByPath.get(containingRoot);
		const owner = packageFor(path, containingRoot, root.id, packageCache);
		const localPath = relative(containingRoot, path).split(sep).join('/');
		const test = isTestPath(path);
		return {
			path,
			displayPath: `${root.id}/${localPath}`,
			root,
			owner,
			concept: conceptFor(path, owner),
			pillar: pillarFor(path, owner),
			test,
			configuredTest: test && isConfiguredTest(path, owner),
			lines: lineCounts(path, source),
			...analyzeAst(path, source)
		};
	});
	const fileSet = new Set(files);
	const packageByName = new Map();
	for (const owner of new Map(records.map((record) => [record.owner.id, record.owner])).values()) {
		const owners = packageByName.get(owner.name) ?? [];
		owners.push(owner);
		packageByName.set(
			owner.name,
			owners.sort((a, b) => a.id.localeCompare(b.id))
		);
	}
	const aliasesByRoot = new Map(
		[...new Map(records.map((record) => [record.owner.root, record.owner])).values()].map(
			(owner) => [owner.root, moduleMappings(owner)]
		)
	);
	const adjacency = new Map(files.map((file) => [file, new Set()]));
	const valueAdjacency = new Map(files.map((file) => [file, new Set()]));
	let externalImports = 0;
	let unresolvedInternalImports = 0;
	for (const record of records) {
		for (const imported of record.imports) {
			const resolution = resolveImport(
				record.path,
				imported.specifier,
				fileSet,
				packageByName,
				record.owner,
				aliasesByRoot
			);
			for (const target of resolution.targets) {
				adjacency.get(record.path).add(target);
				if (!imported.typeOnly) valueAdjacency.get(record.path).add(target);
			}
			if (resolution.targets.length === 0) {
				if (resolution.internal) unresolvedInternalImports += 1;
				else externalImports += 1;
			}
		}
	}
	const production = records.filter((record) => !record.test);
	const testCandidates = records.filter((record) => record.test);
	const tests = testCandidates.filter((record) => record.configuredTest);
	const productionSet = new Set(production.map((record) => record.path));
	const productionAdjacency = new Map(
		production.map((record) => [
			record.path,
			new Set([...adjacency.get(record.path)].filter((target) => productionSet.has(target)))
		])
	);
	const incoming = new Map(production.map((record) => [record.path, 0]));
	let internalEdges = 0;
	let crossConceptEdges = 0;
	const importLocalities = emptyLocality();
	const byPath = new Map(records.map((record) => [record.path, record]));
	const catalogues = receiptPaths.length > 0 ? scannerCatalogues(receiptPaths, roots) : null;
	const quality = catalogues ? staticFindings(catalogues, byPath, rootByPath) : null;
	if (quality) {
		const covered = new Set(
			catalogues.flatMap(({ receipt, inventory }) =>
				inventory.sources.map((file) => join(receipt.root, file))
			)
		);
		const unscanned = production.filter((record) => !covered.has(record.path));
		quality.coverage = {
			productionFiles: production.length - unscanned.length,
			unscannedProductionFiles: unscanned.length,
			unscannedFiles: unscanned.map((record) => record.displayPath).sort(),
			tiers: {
				syntactic: true,
				graph: catalogues.every(({ receipt }) => receipt.tiers.graph),
				typeAware: catalogues.every(({ receipt }) => receipt.tiers.typeAware)
			},
			rootsWithoutTypeAware: catalogues
				.filter(({ receipt }) => !receipt.tiers.typeAware)
				.map(({ receipt }) => receipt.root)
				.sort()
		};
	}
	for (const [from, targets] of productionAdjacency)
		for (const target of targets) {
			internalEdges += 1;
			incoming.set(target, (incoming.get(target) ?? 0) + 1);
			importLocalities[importLocality(byPath.get(from), byPath.get(target))] += 1;
			if (byPath.get(from).concept !== byPath.get(target).concept) crossConceptEdges += 1;
		}
	const cycles = stronglyConnected(productionSet, productionAdjacency);
	const cyclicModules = new Set(cycles.flat()).size;
	const fanOut = production.map((record) => productionAdjacency.get(record.path).size);
	const fanIn = production.map((record) => incoming.get(record.path) ?? 0);
	const fanOutStats = distribution(fanOut);
	const topHubCount = Math.max(1, Math.ceil(production.length * 0.1));
	const hubShare =
		internalEdges === 0
			? 0
			: [...fanIn]
					.sort((a, b) => b - a)
					.slice(0, topHubCount)
					.reduce((sum, value) => sum + value, 0) / internalEdges;
	const coupling =
		100 *
		(0.4 * (crossConceptEdges / Math.max(internalEdges, 1)) +
			0.3 * (cyclicModules / Math.max(production.length, 1)) +
			0.2 * Math.min(1, fanOutStats.p95 / Math.sqrt(Math.max(production.length, 1))) +
			0.1 * hubShare);
	const functions = production.flatMap((record) =>
		record.functions.map((item) => ({
			...item,
			file: record.displayPath,
			concept: record.concept,
			pillar: record.pillar,
			rootId: record.root.id
		}))
	);
	const duplicateEntities = production.flatMap((record) =>
		record.duplicateEntities.map((item) => ({
			...item,
			file: record.displayPath,
			concept: record.concept,
			pillar: record.pillar,
			rootId: record.root.id
		}))
	);
	const pathwayReport = pathwayEvidence(duplicateEntities);
	const duplicatePathways = pathwayReport.exact;
	const overlappingPathways = pathwayReport.overlapping;
	const functionalityClusters = pathwayReport.clusters;
	const structuralInlineCandidates = production
		.flatMap((record) =>
			record.inlineCandidates.map((candidate) => ({
				...candidate,
				file: record.displayPath,
				concept: record.concept,
				pillar: record.pillar
			}))
		)
		.sort(
			(left, right) =>
				left.file.localeCompare(right.file) ||
				left.line - right.line ||
				left.name.localeCompare(right.name)
		);
	const recordByDisplayPath = new Map(production.map((record) => [record.displayPath, record]));
	const inlineCandidates = quality
		? quality.findings
				.filter(({ rule }) => rule === 'Q1' || rule === 'Q3' || rule === 'Q4')
				.map((finding) => {
					const record = recordByDisplayPath.get(finding.file);
					const fields = new Map(
						(finding.evidence ?? '')
							.split(/\s+/)
							.map((field) => field.split('=', 2))
							.filter((field) => field.length === 2)
					);
					return {
						name: fields.get('name') ?? '<unknown>',
						line: finding.line,
						useLine: null,
						kind:
							fields.get('kind') ??
							(finding.rule === 'Q1'
								? 'callback-proxy'
								: finding.rule === 'Q3'
									? 'transparent-forwarder'
									: 'single-use-expression'),
						confidence: finding.rule === 'Q4' ? 'review' : 'high',
						tokens: null,
						file: finding.file,
						concept: record?.concept ?? finding.concept,
						pillar: record?.pillar ?? 'unmapped'
					};
				})
				.sort(
					(left, right) =>
						left.file.localeCompare(right.file) ||
						left.line - right.line ||
						left.name.localeCompare(right.name)
				)
		: structuralInlineCandidates;
	const pillars = buildPillars(
		production,
		productionAdjacency,
		byPath,
		cycles,
		quality,
		inlineCandidates
	);
	const conceptMap = new Map();
	for (const record of production) {
		const concept = conceptMap.get(record.concept) ?? {
			concept: record.concept,
			files: 0,
			codeLoc: 0,
			functions: 0,
			services: [],
			outgoingConcepts: new Set(),
			incomingConcepts: new Set()
		};
		concept.files += 1;
		concept.codeLoc += record.lines.code;
		concept.functions += record.functions.length;
		concept.services.push(...record.services.map((name) => ({ name, file: record.displayPath })));
		conceptMap.set(record.concept, concept);
	}
	for (const [from, targets] of productionAdjacency)
		for (const target of targets) {
			const sourceConcept = byPath.get(from).concept;
			const targetConcept = byPath.get(target).concept;
			if (sourceConcept !== targetConcept) {
				conceptMap.get(sourceConcept).outgoingConcepts.add(targetConcept);
				conceptMap.get(targetConcept).incomingConcepts.add(sourceConcept);
			}
		}
	const concepts = [...conceptMap.values()]
		.map((item) => ({
			...item,
			services: item.services.sort((a, b) => a.name.localeCompare(b.name)),
			fanInConcepts: item.incomingConcepts.size,
			fanOutConcepts: item.outgoingConcepts.size,
			incomingConcepts: undefined,
			outgoingConcepts: undefined
		}))
		.sort((a, b) => b.codeLoc - a.codeLoc || a.concept.localeCompare(b.concept));
	const services = concepts
		.flatMap((concept) =>
			concept.services.map((service) => ({ ...service, concept: concept.concept }))
		)
		.sort((a, b) => a.concept.localeCompare(b.concept) || a.name.localeCompare(b.name));
	const reached = testReach(
		new Set(tests.map((record) => record.path)),
		valueAdjacency,
		productionSet
	);
	const productionCode = production.reduce((sum, record) => sum + record.lines.code, 0);
	const testCode = tests.reduce((sum, record) => sum + record.lines.code, 0);
	const unconfiguredTestCode = testCandidates
		.filter((record) => !record.configuredTest)
		.reduce((sum, record) => sum + record.lines.code, 0);
	const qualityCode = quality
		? production
				.filter((record) => !quality.coverage.unscannedFiles.includes(record.displayPath))
				.reduce((sum, record) => sum + record.lines.code, 0)
		: 0;
	if (quality) quality.coverage.productionCodeLoc = qualityCode;
	if (quality)
		quality.byPrinciple = quality.byPrinciple.map((item) => ({
			...item,
			perThousandProductionLoc:
				qualityCode === 0 ? null : Math.round((item.count / (qualityCode / 1000)) * 1000) / 1000
		}));
	const modularity = 100 - coupling;
	const moduleColocation = localityScore(importLocalities);
	const testability =
		50 * Math.min(1, testCode / Math.max(productionCode * 0.5, 1)) +
		(50 * reached.size) / Math.max(production.length, 1);
	const complexity = distribution(functions.map((item) => item.cyclomatic));
	const nesting = distribution(functions.map((item) => item.nesting));
	const passThrough = functions.filter((item) => item.passThrough).length;
	const simplicity =
		100 *
		(1 -
			(0.45 * Math.min(1, complexity.p95 / 15) +
				0.3 * Math.min(1, nesting.p95 / 8) +
				(0.25 * passThrough) / Math.max(functions.length, 1)));
	const clamp = (value) => Math.max(0, Math.min(100, value));
	const rawScores = {
		coupling: clamp(coupling),
		modularity: clamp(modularity),
		colocation: clamp(moduleColocation),
		testability: clamp(testability),
		simplicity: clamp(simplicity),
		staticQuality: null,
		health: null
	};
	if (quality && quality.coverage.unscannedProductionFiles === 0) {
		const weightedDensity =
			qualityCode === 0
				? quality.totals.error + quality.totals.warning === 0
					? 0
					: Number.POSITIVE_INFINITY
				: (4 * quality.totals.error + quality.totals.warning) / (qualityCode / 1000);
		rawScores.staticQuality = clamp(100 / (1 + weightedDensity));
		rawScores.health = clamp(
			0.3 * rawScores.modularity +
				0.2 * rawScores.testability +
				0.2 * rawScores.simplicity +
				0.3 * rawScores.staticQuality
		);
	}
	const round = (value) => (value === null ? null : Math.round(value * 100) / 100);
	const scores = Object.fromEntries(
		Object.entries(rawScores).map(([name, value]) => [name, round(value)])
	);
	const scorePrecision = Object.fromEntries(
		Object.entries(rawScores).map(([name, value]) => [
			name,
			value === null ? null : Math.round(value * 1_000_000_000_000) / 1_000_000_000_000
		])
	);
	const hotspots = production
		.map((record) => ({
			file: record.displayPath,
			concept: record.concept,
			codeLoc: record.lines.code,
			fanIn: incoming.get(record.path) ?? 0,
			fanOut: productionAdjacency.get(record.path).size,
			p95Complexity: distribution(record.functions.map((item) => item.cyclomatic)).p95
		}))
		.sort((a, b) => b.codeLoc - a.codeLoc || b.fanIn - a.fanIn || a.file.localeCompare(b.file))
		.slice(0, 30);
	return {
		schemaVersion: SCHEMA_VERSION,
		analyzerVersion: ANALYZER_VERSION,
		roots: rootDescriptions,
		totals: {
			files: records.length,
			productionFiles: production.length,
			testFiles: tests.length,
			unconfiguredTestFiles: testCandidates.length - tests.length,
			physicalLoc: records.reduce((sum, record) => sum + record.lines.physical, 0),
			codeLoc: productionCode + testCode + unconfiguredTestCode,
			productionCodeLoc: productionCode,
			testCodeLoc: testCode,
			unconfiguredTestCodeLoc: unconfiguredTestCode,
			commentLoc: records.reduce((sum, record) => sum + record.lines.comments, 0),
			blankLoc: records.reduce((sum, record) => sum + record.lines.blank, 0),
			concepts: concepts.length,
			pillars: pillars.length,
			services: services.length,
			functions: functions.length,
			codeEntities: duplicateEntities.length,
			passThroughFunctions: passThrough,
			inlineCandidates: inlineCandidates.length,
			highConfidenceInlineCandidates: inlineCandidates.filter(
				({ confidence }) => confidence === 'high'
			).length,
			reviewInlineCandidates: inlineCandidates.filter(({ confidence }) => confidence === 'review')
				.length,
			transparentForwarders: inlineCandidates.filter(({ kind }) => kind === 'transparent-forwarder')
				.length,
			callbackProxies: inlineCandidates.filter(({ kind }) => kind === 'callback-proxy').length,
			singleUseExpressions: inlineCandidates.filter(({ kind }) => kind === 'single-use-expression')
				.length,
			sameFileNamedCalls: production.reduce((sum, record) => sum + record.localNamedCalls, 0),
			internalImportEdges: internalEdges,
			crossConceptEdges,
			externalImports,
			unresolvedInternalImports,
			cyclicModules,
			cycleGroups: cycles.length,
			duplicatePathwayGroups: duplicatePathways.length,
			duplicatePathwayOccurrences: duplicatePathways.reduce(
				(sum, group) => sum + group.occurrences.length,
				0
			),
			overlappingPathwayPairs: overlappingPathways.length,
			functionalityClusters: functionalityClusters.length,
			crossConceptFunctionalityClusters: functionalityClusters.filter(
				({ crossConcept }) => crossConcept
			).length,
			crossPillarFunctionalityClusters: functionalityClusters.filter(
				({ crossPillar }) => crossPillar
			).length,
			clusteredEntityOccurrences: functionalityClusters.reduce(
				(sum, cluster) => sum + cluster.members.length,
				0
			),
			testReachedProductionModules: reached.size,
			staticErrors: quality?.totals.error ?? null,
			staticWarnings: quality?.totals.warning ?? null
		},
		scores,
		scorePrecision,
		quality,
		distributions: {
			productionFileCodeLoc: distribution(production.map((record) => record.lines.code)),
			functionCyclomatic: complexity,
			functionNesting: nesting,
			fanIn: distribution(fanIn),
			fanOut: fanOutStats,
			pillarCodeLoc: distribution(pillars.map(({ codeLoc }) => codeLoc)),
			pillarCohesion: distribution(pillars.map(({ cohesion }) => cohesion)),
			pillarComplexityDensity: distribution(
				pillars.map(({ complexity }) => complexity.excessPerThousandLoc)
			),
			pillarIndirectionDensity: distribution(
				pillars.map(({ indirection }) => indirection.perHundredNamedFunctions)
			)
		},
		colocation: {
			importEdges: importLocalities,
			importScore: moduleColocation,
			sameFileNamedCalls: production.reduce((sum, record) => sum + record.localNamedCalls, 0)
		},
		concepts,
		pillars,
		services,
		cycles: cycles.map((component) => component.map((path) => byPath.get(path).displayPath)),
		duplicatePathways,
		overlappingPathways,
		functionalityClusters,
		inlineCandidates,
		hotspots
	};
}

/** Compare score and architecture regressions against a schema-compatible baseline. */
function compare(report, baseline) {
	if (
		baseline.schemaVersion !== report.schemaVersion ||
		baseline.analyzerVersion !== report.analyzerVersion
	)
		throw new Error(
			`baseline analyzer/schema does not match ${report.analyzerVersion}/${report.schemaVersion}`
		);
	if (JSON.stringify(baseline.roots) !== JSON.stringify(report.roots))
		throw new Error('baseline roots do not match the selected roots');
	const deltas = {};
	for (const key of Object.keys(report.scorePrecision))
		if (report.scorePrecision[key] !== null && baseline.scorePrecision[key] !== null)
			deltas[key] =
				Math.round((report.scorePrecision[key] - baseline.scorePrecision[key]) * 1_000_000_000) /
				1_000_000_000;
	for (const key of [
		'productionFiles',
		'productionCodeLoc',
		'concepts',
		'pillars',
		'services',
		'cyclicModules',
		'cycleGroups',
		'duplicatePathwayGroups',
		'duplicatePathwayOccurrences',
		'overlappingPathwayPairs',
		'functionalityClusters',
		'crossConceptFunctionalityClusters',
		'crossPillarFunctionalityClusters',
		'clusteredEntityOccurrences',
		'inlineCandidates',
		'staticErrors',
		'staticWarnings'
	])
		if (report.totals[key] !== null && baseline.totals[key] !== null)
			deltas[key] = report.totals[key] - baseline.totals[key];
	const regressions = [];
	if (deltas.coupling > 0) regressions.push(`coupling +${deltas.coupling}`);
	for (const key of [
		'modularity',
		'colocation',
		'testability',
		'simplicity',
		'staticQuality',
		'health'
	])
		if ((deltas[key] ?? 0) < 0) regressions.push(`${key} ${deltas[key]}`);
	for (const key of [
		'cyclicModules',
		'cycleGroups',
		'duplicatePathwayGroups',
		'duplicatePathwayOccurrences',
		'overlappingPathwayPairs',
		'functionalityClusters',
		'crossConceptFunctionalityClusters',
		'crossPillarFunctionalityClusters',
		'clusteredEntityOccurrences',
		'inlineCandidates',
		'staticErrors',
		'staticWarnings'
	])
		if ((deltas[key] ?? 0) > 0) regressions.push(`${key} +${deltas[key]}`);
	return { deltas, regressions };
}

/** Render the bounded decision brief; exact evidence remains in JSON. */
function markdown(report) {
	const staticTiers = report.quality
		? [
				'syntactic',
				...(report.quality.coverage.tiers.graph ? ['graph'] : []),
				...(report.quality.coverage.tiers.typeAware ? ['type-aware'] : [])
			].join(' + ')
		: '';
	const lines = [
		'# Repository health',
		'',
		`Verdict: **${report.verdict}**`,
		'',
		report.quality
			? `Tiers: ${staticTiers}${!report.quality.coverage.tiers.graph ? ' only — **graph rules not run**, so reachability, dead exports, and cycles are unevaluated' : !report.quality.coverage.tiers.typeAware ? ' only — **type-aware not run**, so LEGACY2 and every other type-resolved rule is unevaluated' : ''}`
			: 'Tiers: no static evidence',
		'',
		'## Snapshot',
		'',
		'| Metric | Value |',
		'| --- | ---: |'
	];
	for (const [label, value] of [
		['Production files', report.totals.productionFiles],
		['Configured test files', report.totals.testFiles],
		['Unconfigured test files', report.totals.unconfiguredTestFiles],
		['Production code LOC', report.totals.productionCodeLoc],
		['Test code LOC', report.totals.testCodeLoc],
		['Unconfigured test code LOC', report.totals.unconfiguredTestCodeLoc],
		['Comment LOC (excluded)', report.totals.commentLoc],
		['Concepts', report.totals.concepts],
		['Pillars', report.totals.pillars],
		['Services', report.totals.services],
		['Named code entities', report.totals.codeEntities],
		['Internal edges', report.totals.internalImportEdges],
		['Unresolved internal imports', report.totals.unresolvedInternalImports],
		['Cross-concept edges', report.totals.crossConceptEdges],
		['Cyclic modules', report.totals.cyclicModules],
		['Duplicate entity groups', report.totals.duplicatePathwayGroups],
		['Overlapping entity pairs', report.totals.overlappingPathwayPairs],
		['Functionality clusters', report.totals.functionalityClusters],
		['Cross-concept functionality clusters', report.totals.crossConceptFunctionalityClusters],
		['Cross-pillar functionality clusters', report.totals.crossPillarFunctionalityClusters],
		['Inline candidates', report.totals.inlineCandidates],
		['High-confidence inline candidates', report.totals.highConfidenceInlineCandidates],
		['Review-only inline candidates', report.totals.reviewInlineCandidates],
		['Same-file named calls', report.totals.sameFileNamedCalls],
		['Pass-through functions', report.totals.passThroughFunctions]
	])
		lines.push(`| ${label} | ${value} |`);
	lines.push(
		'',
		'## Scores',
		'',
		'| Coupling ↓ | Modularity ↑ | Colocation ↑ | Testability ↑ | Simplicity ↑ | Static quality ↑ | Health ↑ |',
		'| ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
		`| ${report.scores.coupling} | ${report.scores.modularity} | ${report.scores.colocation} | ${report.scores.testability} | ${report.scores.simplicity} | ${report.scores.staticQuality ?? 'not scanned'} | ${report.scores.health ?? 'not scored'} |`
	);
	if (report.quality) {
		lines.push(
			'',
			`Static findings: ${report.quality.totals.error} errors, ${report.quality.totals.warning} warnings, ${report.quality.totals.hint} hints.`,
			'',
			'## Findings by principle',
			'',
			'| Principle | Findings | Per 1,000 production LOC |',
			'| --- | ---: | ---: |'
		);
		for (const item of report.quality.byPrinciple)
			lines.push(`| ${item.name} | ${item.count} | ${item.perThousandProductionLoc ?? 'n/a'} |`);
		lines.push('', '## Largest static-debt rules', '', '| Rule | Findings |', '| --- | ---: |');
		for (const item of report.quality.byRule.slice(0, 15))
			lines.push(`| ${item.name} | ${item.count} |`);
	}
	if (report.comparison)
		lines.push(
			'',
			`Baseline regressions: ${report.comparison.regressions.length === 0 ? 'none' : report.comparison.regressions.join(', ')}`
		);
	lines.push(
		'',
		'## Largest concepts',
		'',
		'| Concept | Code LOC | Files | Services | Concept fan-in | Concept fan-out |',
		'| --- | ---: | ---: | ---: | ---: | ---: |'
	);
	for (const concept of report.concepts.slice(0, 20))
		lines.push(
			`| ${concept.concept} | ${concept.codeLoc} | ${concept.files} | ${concept.services.length} | ${concept.fanInConcepts} | ${concept.fanOutConcepts} |`
		);
	lines.push(
		'',
		'## Domain pillars',
		'',
		'| Pillar | LOC | Files | Child concepts | Cohesion | Colocation | Complexity/1k LOC | Inline high/review |',
		'| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |'
	);
	for (const pillar of report.pillars.slice(0, 25))
		lines.push(
			`| ${pillar.label} | ${pillar.codeLoc} | ${pillar.files.length} | ${pillar.concepts.length} | ${(pillar.cohesion * 100).toFixed(1)}% | ${pillar.colocation.importScore} | ${pillar.complexity.excessPerThousandLoc} | ${pillar.indirection.highConfidence}/${pillar.indirection.review} |`
		);
	lines.push(
		'',
		'## Highest-LOC modules',
		'',
		'| File | Concept | Code LOC | Fan-in | Fan-out | p95 complexity |',
		'| --- | --- | ---: | ---: | ---: | ---: |'
	);
	for (const item of report.hotspots.slice(0, 15))
		lines.push(
			`| ${item.file} | ${item.concept} | ${item.codeLoc} | ${item.fanIn} | ${item.fanOut} | ${item.p95Complexity} |`
		);
	if (report.functionalityClusters.length) {
		lines.push(
			'',
			'## Functionality clusters',
			'',
			'| Label | Members | Pillars | Cyclomatic p95 | Excess | Pass-through | Same-pillar | Density |',
			'| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |'
		);
		for (const cluster of report.functionalityClusters.slice(0, 20))
			lines.push(
				`| ${cluster.label} | ${cluster.members.length} | ${cluster.pillars.length} | ${cluster.complexity.cyclomatic.p95} | ${cluster.complexity.excessCyclomatic} | ${cluster.indirection.passThroughMembers} | ${(cluster.colocation.samePillarShare * 100).toFixed(1)}% | ${(cluster.overlapDensity * 100).toFixed(1)}% |`
			);
	}
	lines.push(
		'',
		`Cycles: ${report.totals.cycleGroups}. Exact duplicate groups: ${report.totals.duplicatePathwayGroups}. High-confidence overlap pairs: ${report.totals.overlappingPathwayPairs}. Read the JSON report for exact evidence.`,
		''
	);
	return lines.join('\n');
}

/** Atomically publish one output file; JSON and Markdown are not a transactional pair. */
function atomicWrite(path, content) {
	mkdirSync(dirname(path), { recursive: true });
	const temporary = `${path}.${process.pid}.tmp`;
	writeFileSync(temporary, content);
	renameSync(temporary, path);
}

/** Normalize an explicit single-format extension when one path names a JSON/Markdown pair. */
function pairedOutputRoot(path) {
	return path.replace(/\.(?:json|md)$/i, '');
}

/** Execute the scan with stable default outputs and explicit regression semantics. */
function main() {
	const options = parseArguments(process.argv.slice(2));
	if (options.help) {
		process.stdout.write(usage());
		return;
	}
	if (options.overlapOnly) {
		const report = analyzeOverlaps(options.roots);
		const json = `${JSON.stringify(report, null, 2)}\n`;
		const brief = `${overlapMarkdown(report)}\n`;
		const outputRoot = options.out ?? resolve('.norbital/diagnosis/overlap');
		if (options.format === 'json') {
			if (options.out) atomicWrite(outputRoot, json);
			else process.stdout.write(json);
		} else if (options.format === 'markdown') {
			if (options.out) atomicWrite(outputRoot, brief);
			else process.stdout.write(brief);
		} else {
			const pairRoot = pairedOutputRoot(outputRoot);
			atomicWrite(`${pairRoot}.json`, json);
			atomicWrite(`${pairRoot}.md`, brief);
			process.stdout.write(brief);
		}
		if (report.verdict === 'findings') process.exitCode = 1;
		return;
	}
	const report = analyze(options.roots, options.receipts);
	if (options.baseline)
		report.comparison = compare(report, JSON.parse(readFileSync(options.baseline, 'utf8')));
	report.verdict =
		options.receipts.length === 0 ||
		report.quality.coverage.unscannedProductionFiles > 0 ||
		(options.requireTypeAware && !report.quality.coverage.tiers.typeAware)
			? 'incomplete'
			: report.quality.totals.error + report.quality.totals.warning > 0
				? 'fail'
				: options.failOnRegression && (report.comparison?.regressions.length ?? 0) > 0
					? 'regression'
					: 'pass';
	const json = `${JSON.stringify(report, null, 2)}\n`;
	const brief = `${markdown(report)}\n`;
	const outputRoot = options.out ?? resolve('.norbital/diagnosis/report');
	if (options.format === 'json') {
		if (options.out) atomicWrite(outputRoot, json);
		else process.stdout.write(json);
	} else if (options.format === 'markdown') {
		if (options.out) atomicWrite(outputRoot, brief);
		else process.stdout.write(brief);
	} else {
		const pairRoot = pairedOutputRoot(outputRoot);
		atomicWrite(`${pairRoot}.json`, json);
		atomicWrite(`${pairRoot}.md`, brief);
		process.stdout.write(brief);
	}
	if (report.verdict === 'regression' || report.verdict === 'fail') process.exitCode = 1;
	if (report.verdict === 'incomplete') process.exitCode = 2;
}

try {
	main();
} catch (error) {
	process.stderr.write(
		`repository-health: ${error instanceof Error ? error.message : String(error)}\n`
	);
	process.exitCode = 2;
}
