/** The UI's fixed messages share one fallback table. */
export function msg(
	bolt: Pick<ViewBolt, 't'>,
	key: keyof typeof MESSAGES,
	vars: { readonly [n: string]: string | number } = {}
): string {
	return catalogText(bolt, key, MESSAGES[key], vars);
}
/** The ui's own keys (`ui.*`) fall back to English outside a catalog. */
export function catalogText(
	bolt: Pick<ViewBolt, 't'>,
	key: string,
	fallback: string,
	vars: { readonly [n: string]: string | number } = {}
): string {
	const s = bolt.t(`ui.${key}`, vars);
	return s === `ui.${key}` ? fill(fallback, vars) : s;
}
/**
 * A model's or field's label: the catalog key, else the field's `declared` label, else the humanized name; a FK names its target (`project_id` → `Project`).
 */
export function label(
	bolt: Pick<ViewBolt, 't'>,
	model: string,
	field?: string,
	declared?: string
): string {
	const key =
		field === undefined ? `models.${model}.label` : `models.${model}.fields.${field}`;
	const s = bolt.t(key);
	return s !== key ? s : (declared ?? NATIVE_FIELDS[key] ?? humanize((field ?? model).replace(/_id$/, '')));
}
/** A label inside a sentence: its first letter lowered unless it leads an acronym (`Jobs` → `jobs`, `SOW documents` stays). */
export const lowerLead = (s: string) =>
	/^\p{Lu}\p{Ll}/u.test(s) ? s.charAt(0).toLowerCase() + s.slice(1) : s;
/** One record of a model: the catalog's `models.<c>.singular`, else its label made singular (`Categories` → `Category`). */
export function singular(bolt: Pick<ViewBolt, 't'>, model: string): string {
	const key = `models.${model}.singular`,
		s = bolt.t(key);
	return s !== key
		? s
		: label(bolt, model)
				.replace(/ies$/, 'y')
				.replace(/(ss|x|ch|sh)es$/, '$1')
				.replace(/([^su])s$/, '$1');
}
